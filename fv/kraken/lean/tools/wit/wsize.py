import sys,subprocess; sys.path.insert(0,sys.argv[1]); import wgen
# Witnesses of the SizeSSZ theorems (re-proof R6): a return slot and, for the
# variable-size types, the length word at rax + 8 (n = 3).
Z="Int.toBytes 8 (0 : UInt64).toBitVec.toInt"
L="Int.toBytes 8 (BitVec.ofNat 64 3).toInt"
T=[("sc","ScSize","ScalarsSizeSSZ","target.Scalars.SizeSSZ",False,"16"),
   ("fv","FvSmall","FixedVecSizeSSZ","target.FixedVec.SizeSSZ",False,"64"),
   ("bv","BvSpec","BitVecSizeSSZ","target.BitVec.SizeSSZ",False,"1"),
   ("cp","CpSpec","PrysmCheckpointSizeSSZ","target_prysm.Checkpoint.SizeSSZ",False,"40"),
   ("ad","AdSpec","PrysmAttestationDataSizeSSZ","target_prysm.AttestationData.SizeSSZ",False,"128"),
   ("lu","LuMarshal","ListU64SizeSSZ","target.ListU64.SizeSSZ",True,"4 + 8 * 3"),
   ("bl","BlSpec","BitLSizeSSZ","target.BitL.SizeSSZ",True,"4 + 3")]
for key,mod,prog,sfile,var,val in T:
    tlen=int(subprocess.check_output(["grep","-c","",f"../link/out/norm/{sfile}.S"]).strip())
    # Go values (re-proof fix X4): a fixed-size SizeSSZ does not read c, so c is
    # nil; a variable-size c is a full header (p, 3, 3) and its data.
    esz=8 if key=="lu" else 1
    ch=[("ra",Z,8)]+([("gap_p",f"Int.toBytes 8 ({0x10020:#x} : BitVec 64).toInt",8),("len",L,8),("gap_c",L,8),("gap_d",f"z {3*esz}",3*esz)] if var else [])
    prem=f"Eq (({Z}).At s.regs.rsp.toBitVec)"+(f"\n      ⋆ Eq (({L}).At (s.regs.rax.toBitVec + 8))" if var else "")
    args="(s0 zmms flags) 0 3 (by decide)" if var else "(s0 zmms flags) 0"
    concl=("st.data.regs.rax.toNat = "+val) if var else ("st.data.regs.rax = "+val)
    proj="⟨h.1, h.2⟩" if key=="sc" else "⟨h.1, h.2.1⟩"
    cfg=dict(ns=f"WitSz{key.capitalize()}",imports=[f"import Fk.{mod}"],doc=f"""# Premise witness of `{key}_size_main` (re-proof R6)

Host: data labels and the real {sfile} (index 5). Generated by `tools/wit/wsize.py`.""",
      target=prog,tlen=tlen,models=[],chunks=ch,pbinders="",pnames="",lenhyps="",lenhypnames=[],
      regs=lambda a,var=var: f"{hex(a['gap_p']) if var else 0}, 0, 0, 0, 0, 0, {hex(a['ra'])}, 0, 0, 0, 0, 0, 0, 0, 0, 0",
      premise=prem, main=lambda st,k=key,args=args,concl=concl,proj=proj: f"""/-- **Non-vacuity of `{k}_size_main`.** -/
theorem {k}_size_runs (zmms : RegZmms) (flags : StatusFlags) :
    Eventually (step1 Host.exe)
      (fun st => st.pc = Int64.ofBitVec (0 : UInt64).toBitVec ∧ {concl})
      ⟨s0 zmms flags, Host.addrOf 5⟩ :=
  eventually_mono ({k}_size_main 5 hk_target {args} (fun _ => True) (s_mem zmms flags))
    (fun _ h => {proj})
""")
    src,addr,starts=wgen.gen2(cfg)
    src=src.replace("  apply sep_true (F := )\n","  apply sep_true (F := Std.ExtHashMap.emp)\n  simp only [Std.ExtHashMap.sep_emp]\n",1)
    open(f"Fk/WitSz{key.capitalize()}.lean","w").write(src)
    print(key, tlen)
