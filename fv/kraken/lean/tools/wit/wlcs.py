import sys,subprocess; sys.path.insert(0,sys.argv[1]); import wgen
# Witnesses of lc_size_main (ListC.SizeSSZ; re-proof fix X8): n = 0, 1, 4
# elements. Every element is a full Go ListU64 object (data pointer, len, cap)
# with its data; the receiver header is (q, n, n). argv[2] = n.
N=int(sys.argv[2])
LS={0:[],1:[1],4:[0,1,2,16]}[N]
Z="Int.toBytes 8 (0 : UInt64).toBitVec.toInt"
def W(v): return f"Int.toBytes 8 ({v:#x} : BitVec 64).toInt"
tlen=int(subprocess.check_output(["grep","-c","","../link/out/norm/target.ListC.SizeSSZ.S"]).strip())
# layout: ra, header (q, n, cap), pointer array, element objects, element data
base=0x10000
a_ra=base; a_h=a_ra+8; a_arr=a_h+24; a_obj=a_arr+8*N; a_dat=a_obj+24*N
dat=[]; d=a_dat
for l in LS: dat.append(d if l else 0); d+=8*l
ch=[("ra",Z,8),("q",W(a_arr) if N else W(0),8),("n",f"Int.toBytes 8 (BitVec.ofNat 64 {N}).toInt",8),("gap_hc",f"Int.toBytes 8 (BitVec.ofNat 64 {N}).toInt",8)]
for i in range(N): ch.append((f"gap_a{i}",W(a_obj+24*i),8))
for i,l in enumerate(LS):
    ch+=[(f"gap_q{i}",W(dat[i]),8),(f"gap_l{i}",f"Int.toBytes 8 (BitVec.ofNat 64 {l}).toInt",8),(f"gap_c{i}",f"Int.toBytes 8 (BitVec.ofNat 64 {l}).toInt",8)]
for i,l in enumerate(LS):
    if l: ch.append((f"gap_d{i}",f"z {8*l}",8*l))
Q=hex(a_arr) if N else "0"
prem=f"""Eq (({Z}).At s.regs.rsp.toBitVec)
      ⋆ Eq ((Int.toBytes 8 ({Q} : BitVec 64).toInt).At s.regs.rax.toBitVec)
      ⋆ Eq ((Int.toBytes 8 (BitVec.ofNat 64 {N}).toInt).At (s.regs.rax.toBitVec + 8))"""
PS="["+", ".join(f"({a_obj+24*i:#x} : BitVec 64)" for i in range(N))+"]"
LSS="["+", ".join(map(str,LS))+"]"
# hall_i: the pointer word i and the length word of element i, from the block
def hall(i):
    pick={f"gap_a{i}",f"gap_l{i}"}
    rest=[(k,e,n) for k,e,n in ch if k not in pick]
    addr={}; a=base
    for k,e,n in ch: addr[k]=a; a+=n
    F=" ⋆ ".join(f"Eq (α := Std.ExtHashMap (BitVec 64) UInt8) (({e}).At {addr[k]}#64)" for k,e,n in rest)
    return f"""set_option maxHeartbeats 8000000 in
set_option maxRecDepth 100000 in
theorem hall_{i} (zmms : RegZmms) (flags : StatusFlags) :
    (Eq ((Int.toBytes 8 ({a_obj+24*i:#x} : BitVec 64).toInt).At (({Q} : BitVec 64) + BitVec.ofNat 64 (8 * {i})))
      ⋆ Eq ((Int.toBytes 8 (BitVec.ofNat 64 {LS[i]}).toInt).At (({a_obj+24*i:#x} : BitVec 64) + 8)) ⋆ fun _ => True)
      (s0 zmms flags).dmem := by
  have H : Eq ((block ).At (0x10000 : BitVec 64)) (mem ) := rfl
  conv at H => lhs; unfold block
  repeat rw [Mem.At_append_sep _ _ _ (by simp only [List.length_append, List.length_replicate, Int.toBytes_length, List.length_cons, List.length_nil]; omega)] at H
  simp only [List.length_replicate, Int.toBytes_length, List.length_cons, List.length_nil, Nat.reduceAdd,
    BitVec.ofNat_eq_ofNat, BitVec.reduceAdd] at H
  simp only [s0, BitVec.ofNat_eq_ofNat, BitVec.reduceAdd, BitVec.reduceMul, Nat.reduceMul]
  apply sep_true (F := {F})
  try simp only [BitVec.ofNat_eq_ofNat, BitVec.reduceAdd] at H ⊢
  refine Eq.mp ?_ H
  exact congrFun (by ac_rfl) _
"""
halls="".join(hall(i) for i in range(N))
hallarg="(by intro i hi; simp at hi)" if N==0 else ("(by intro i hi; simp only [List.length_cons, List.length_nil] at hi; match i, hi with "
    +" ".join(f"| {i}, _ => exact hall_{i} zmms flags" for i in range(N))+f" | _ + {N}, h => omega)")
cfg=dict(ns=f"WitLcS{N}",imports=["import Fk.LcSize"],doc=f"""# Premise witness of `lc_size_main` (re-proof fix X8), {N} elements

ListC.SizeSSZ on {N} elements of lengths {LS}. Every element is a full Go
ListU64 object (data pointer, len, cap) with its data; the receiver header is
(q, {N}, {N}). Generated by `tools/wit/wlcs.py {N}`.""",
 target="ListCSizeSSZ",tlen=tlen,models=[],chunks=ch,pbinders="",pnames="",lenhyps="",lenhypnames=[],
 regs=lambda a: f"{hex(a['q'])}, 0, 0, 0, 0, 0, {hex(a['ra'])}, 0, 0, 0, 0, 0, 0, 0, 0, 0",
 premise=prem,
 main=lambda st: halls+f"""set_option maxHeartbeats 8000000 in
/-- **Non-vacuity of `lc_size_main`** ({N} elements, lengths {LS}). -/
theorem lc_size_runs (zmms : RegZmms) (flags : StatusFlags) :
    Eventually (step1 Host.exe)
      (fun st => st.pc = Int64.ofBitVec (0 : UInt64).toBitVec ∧ st.data.regs.rax.toNat = lcAcc {LSS} {N})
      ⟨s0 zmms flags, Host.addrOf 5⟩ :=
  eventually_mono (lc_size_main 5 hk_target hf_target ({Q} : BitVec 64) {PS} {LSS} rfl (by decide) (by decide)
    (s0 zmms flags) 0 (fun _ => True) (s_mem zmms flags) {hallarg})
    (fun _ h => ⟨h.1, h.2.1⟩)
""")
src,addr,starts=wgen.gen2(cfg)
wgen.write(f"Fk/WitLcS{N}.lean", src)
print(addr)
