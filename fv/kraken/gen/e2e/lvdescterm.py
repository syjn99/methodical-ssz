#!/usr/bin/env python3
"""Render the `ssz` term of a Desc-checker input file (schema fvphase1c.desc/1) as Lean.

A new file with the method of `descterm.py` (not changed); it also renders `bitVector`, `vector` and `list`.
Usage: lvdescterm.py <desc.json> <lean-name> > lean/E2eList/<X>SpecChecker.lean
The file is the producer's Desc that the Desc checker accepted (gen/desc/results/main.result.json, same sha256;
copies in prysm/go1.26.10/e2e/lv/desc/). Python 3 standard library only.
"""
import hashlib
import json
import sys

path, name = sys.argv[1:3]
raw = open(path, "rb").read()
d = json.loads(raw)
assert d["schema"] == "fvphase1c.desc/1"


def term(t):
    k = t["k"]
    if k == "uint":
        return f".uint {int(t['w'])}"
    if k == "byteVector":
        return f".byteVector {int(t['n'])}"
    if k == "bitVector":
        return f".bitVector {int(t['n'])}"
    if k == "vector":
        return f".vector ({term(t['elem'])}) {int(t['n'])}"
    if k == "list":
        return f".list ({term(t['elem'])}) {int(t['limit'])}"
    if k == "container":
        names = ", ".join(json.dumps(n) for n in t["names"])
        fields = ", ".join(term(f) for f in t["fields"])
        return f".container [{names}] [{fields}]"
    raise SystemExit(f"kind {k} not rendered")


print(f"""import EthLib.Serialization.Ssz

/-! Generated by `gen/e2e/lvdescterm.py` from `prysm/go1.26.10/e2e/lv/desc/{path.rsplit('/', 1)[-1]}`
(sha256 `{hashlib.sha256(raw).hexdigest()}`): the producer's Desc of
`({d['package']}, {d['type']})` that the Desc checker accepted
(`gen/desc/results/main.result.json`, same sha256). Do not edit. -/

namespace E2eList
open EthLib.Serialization.Ssz

def {name} : Desc := {term(d['ssz'])}

end E2eList""")
