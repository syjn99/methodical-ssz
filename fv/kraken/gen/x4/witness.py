#!/usr/bin/env python3
"""Full-premise witness of a generated composition theorem (X4).

Usage: witness.py <regen-dir> <Wit name> <hand theorem> <generated theorem> <generated module> <out.lean>
       witness.py --runs <Fk module file> <runs theorem> <hand theorem> <generated theorem> <generated module> <out.lean>
Takes the witness that gen/wit regenerated (byte-identical to lean/Fk, see gen/wit/results/regen.json),
and retargets it to the generated theorem: import, theorem name and namespace change; the concrete
host, block, s_mem and every argument stay. The witness then shows that every premise of the
generated theorem holds on one concrete Host. Python 3 standard library only.
"""
import os
import sys

if sys.argv[1] == "--runs":
    # A non-vacuity theorem inside a hand witness module that gen/wit does not regenerate (for example
    # lu_accept_runs in Fk/Witness.lean): copy that theorem and the `example`s after it, apply the
    # generated theorem instead of the hand one, and import the hand module only for its concrete
    # Host, memory and contract instances.
    src_file, runs, hand, gen, mod, out = sys.argv[2:8]
    lines = open(src_file).read().split("\n")
    ns = next(l.split()[1] for l in lines if l.startswith("namespace "))
    i = next(j for j, l in enumerate(lines) if l.startswith(f"theorem {runs} "))
    while i > 0 and (lines[i - 1].startswith("/--") or lines[i - 1].startswith(" ") or lines[i - 1].startswith("(")):
        i -= 1
    j = next(j for j in range(i, len(lines)) if lines[j].startswith("example"))
    while j < len(lines) and lines[j].startswith("example"):
        j += 1
    block = "\n".join(lines[i:j])
    assert block.count(f"({hand} ") == 1, f"{hand} must be applied once"
    block = block.replace(f"({hand} ", f"({gen} ", 1)
    modname = os.path.relpath(src_file, os.path.join(os.path.dirname(src_file), "..")).removesuffix(".lean").replace("/", ".")
    name = os.path.basename(out).removesuffix(".lean")
    text = (f"-- Generated by fv/kraken/gen/x4/witness.py --runs from {modname}.{runs} (retargeted from {hand} to {gen}).\n"
            f"import {modname}\nimport {mod}\n\nopen Fk Fk.Code {ns}\n\nnamespace Gen1cX4.{name}\n\n{block}\n\nend Gen1cX4.{name}\n")
    open(out, "w").write(text)
    print(out)
    sys.exit(0)

regen, wit, hand, gen, mod, out = sys.argv[1:7]
src = open(f"{regen}/{wit}.lean").read()
imp = [l for l in src.split("\n") if l.startswith("import Fk.Compose")]
assert len(imp) == 1, imp
assert src.count(f"({hand} ") == 1, f"{hand} must be applied once"
src = src.replace(imp[0], f"import {mod}", 1).replace(f"({hand} ", f"({gen} ", 1)
src = src.replace(f"namespace Fk.{wit}", f"namespace Gen1cX4.{wit}", 1).replace(f"end Fk.{wit}", f"end Gen1cX4.{wit}", 1)
src = "-- Generated by fv/kraken/gen/x4/witness.py from gen/wit output " + wit + f" (retargeted from {hand} to {gen}).\n" + src
open(out, "w").write(src)
print(out)
