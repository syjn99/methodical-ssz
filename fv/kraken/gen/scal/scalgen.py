            f"Eq ((Int.toBytes 8 s.regs.rbx.toBitVec.toInt).At ({sp0} + 16))",
            f"Eq (spl'.At ({sp0} - 40))", f"Eq ((Int.toBytes 8 {P[byt[-1]]}.toInt).At ({sp0} - 16))",
            f"Eq ((Int.toBytes 8 (Host.addrOf (k + {ret})).toBitVec.toInt).At ({sp0} - 48))",
