#!/usr/bin/env python3
"""Scalability stage S2 (INBOX 011): untrusted proof-text generator for the S1 segment lemmas.

Reads a committed normalized `.S` file (`link/norm/*.S`, one directive per non-empty line) and,
for P2, the IR (`prysm/ir/ir-mainnet.json`: SSZ fixed sizes of the fields and the gc amd64 Go
field offsets). Emits Lean text that applies the parameterized lemmas of `lean/E2eScal`:

  p1     the accept path of a uint64 primitive `UnmarshalSSZ` (`E2eScal.u64dec_accept`);
         emits the whole function theorem (P1 statement kind) for the code constant.
  p2dec  for every 32-byte `[]byte` field of a container decoder, the decode segment
         (`E2eScal.rootdec_seg`) as a theorem about the function's code constant.

Statement check (audit AU-08, review fix-r1 M2 and S1): every emitted theorem `t` is followed by
`t_kind : ∀ (h : Host), type_of% (@t h) = <kind> h <parameters>` proved by `with_reducible rfl`. The kind
is hand text in `lean/E2eScal/Kind.lean` (`u64DecAcceptKind`, `rootDecSegKind`), proved from the lemma
there (`*_of`) and, for P1, equal to the reviewed hand statements (`KindAnchor.lean`). `@t h` is the whole
declared type, binders before and after the colon. So the kernel checks the full emitted statement against
the frozen kind; it does not need a hand theorem of the instance type. What it does not check: that the
parameters given to the kind are the right ones for the Go type. A wrong parameter gives a statement that
the code facts of the proof do not support, so the build fails; that is a property of the proof, not of
the `_kind` check. The proof ends in `with_reducible exact <lemma instance>`, so a statement literal that
differs from the lemma instance fails without unfolding `Int.toBytes` (review fix-r1 S2).

Nothing here is trusted: the output is ordinary Lean, checked by the kernel. A wrong read of
the `.S` (wrong label, index, displacement) makes the code hypotheses of the lemma
unprovable and the generated file fails to build. The generator also checks every directive
of a template textually and stops (exit 2, message on stderr) when one does not match: a
compiler variation that the template does not cover is reported, not patched.

Python 3 standard library only. Usage:
  scalgen.py p1 --S FILE --const LEAN_CONST --name THM [--same-as HAND_THM] --imports M1,M2 [--open NS]
  scalgen.py p2dec --S FILE --const LEAN_CONST --ir IR.json --type PKGSUFFIX.TYPE --prefix NAME
                   --imports M1,M2 [--open NS]
"""
import argparse, hashlib, json, pathlib, re, sys

HEX = r"0x[0-9a-f]+"


class NoMatch(Exception):
    pass


def read_S(path):
    raw = pathlib.Path(path).read_bytes()
    lines = [l.strip() for l in raw.decode("ascii").split("\n")]
    return [l for l in lines if l], hashlib.sha256(raw).hexdigest()


def label_of(d):
    return d[:-1] if d.endswith(":") else None


def expect(dirs, i, rx, what):
    if i >= len(dirs):
        raise NoMatch(f"directive {i}: end of file, expected {what}")
    m = re.fullmatch(rx, dirs[i])
    if not m:
        raise NoMatch(f"directive {i}: `{dirs[i]}` is not {what} (/{rx}/)")
    return m


def label_index(dirs, l):
    for i, d in enumerate(dirs):
        if label_of(d) == l:
            return i
    raise NoMatch(f"label {l} not found")


def lean_str(s):
    if '"' in s or "\\" in s:
        raise NoMatch(f"label with a quote or backslash: {s}")
    return f'"{s}"'


def header(src_sha, src, args, extra=""):
    mods = args.imports.split(",")
    mods = mods + [m for m in ["E2eScal.Kind"] if m not in mods]  # the frozen statement kinds
    imports = "\n".join(f"import {m}" for m in mods)
    return (f"{imports}\n\n/-! Generated by `gen/scal/scalgen.py {args.mode}` from `{src}`\n"
            f"(sha256 `{src_sha}`){extra}. Untrusted generator: this file is checked by Lean like any other.\n"
            f"Do not edit by hand (manual edits are measured against the committed raw output). -/\n\n"
            f"open Fk {args.open}\nvariable [Host]\n\nnamespace E2eScal.Gen\n\n")


SIMP_INFIX = ("List.drop_succ_cons, List.drop_zero, List.length_cons, List.length_nil, List.take_succ_cons, "
              "List.take_zero")


def infix_have(name, tmpl_call, at, const):
    return (f"  have {name} := E2eScal.infix_sub (q := {tmpl_call}) {at} hk\n"
            f"    (by simp only [{const}, {tmpl_call.split()[0]}, {SIMP_INFIX}])\n")


def label_have(name, j, const):
    return (f"  have {name} := Fk.label_at' hk hf (j := {j})\n"
            f"    (by simp only [{const}, List.getElem?_cons_succ, List.getElem?_cons_zero]; rfl)\n"
            f"    (by simp only [{const}, List.take_succ_cons, List.take_zero, List.contains_cons, List.contains_nil]; decide)\n")


def kind_thm(name, kind):
    """Review fix-r1 M2/S1: the whole declared type of `name` (binders before the colon included) is the
    frozen statement kind. Emitted directly after the theorem; `negative.py` keeps it in a mutant of `name`."""
    return (f"theorem {name}_kind : ∀ (h : Host), type_of% (@{name} h) = @{kind} := by\n"
            f"  intro h; with_reducible rfl\n")


# ---------------------------------------------------------------- P1

P1_STMT = """theorem {name} (k : Nat) (hk : {const}.IsInfixAt Host.prog k)
    (hf : LabelsFresh {const} k)
    (e8 : List UInt8) (he8 : e8.length = 8)
    (s : MachineData) (ra guard : UInt64) (fp s2 c0 : List UInt8)
    (hfp : fp.length = 8) (h2 : s2.length = 8) (hc0 : c0.length = 8) (R : DataMem → Prop)
    (h_mem : s.dmem =⋆ Eq ((Int.toBytes 8 ra.toBitVec.toInt).At s.regs.rsp.toBitVec)
      ⋆ Eq (fp.At (s.regs.rsp.toBitVec - 8)) ⋆ Eq (s2.At (s.regs.rsp.toBitVec + 16))
      ⋆ Eq ((Int.toBytes 8 guard.toBitVec.toInt).At (s.regs.r14.toBitVec + 16))
      ⋆ Eq (e8.At s.regs.rbx.toBitVec) ⋆ Eq (c0.At s.regs.rax.toBitVec) ⋆ R)
    (hguard : guard.toNat < s.regs.rsp.toNat) (hlen : s.regs.rcx = 8) :
    Eventually (step1 Host.exe)
      (fun st => st.pc = Int64.ofBitVec ra.toBitVec ∧ st.data.regs.rax = 0 ∧ st.data.regs.rbx = 0
        ∧ st.data.regs.rsp = s.regs.rsp + 8 ∧ st.data.regs.rbp = s.regs.rbp ∧ st.data.regs.r14 = s.regs.r14
        ∧ (Eq ((Int.toBytes 8 ra.toBitVec.toInt).At s.regs.rsp.toBitVec)
          ⋆ Eq ((Int.toBytes 8 s.regs.rbp.toBitVec.toInt).At (s.regs.rsp.toBitVec - 8))
          ⋆ Eq ((Int.toBytes 8 s.regs.rbx.toBitVec.toInt).At (s.regs.rsp.toBitVec + 16))
          ⋆ Eq ((Int.toBytes 8 guard.toBitVec.toInt).At (s.regs.r14.toBitVec + 16))
          ⋆ Eq (e8.At s.regs.rbx.toBitVec) ⋆ Eq (e8.At s.regs.rax.toBitVec) ⋆ R) st.data.dmem)
      ⟨s, Host.addrOf k⟩ := by
"""


def p1_read(dirs):
    fn = label_of(dirs[0]) or (_ for _ in ()).throw(NoMatch("directive 0 is not a label"))
    l0 = label_of(dirs[1]) or (_ for _ in ()).throw(NoMatch("directive 1 is not a label"))
    expect(dirs, 2, r"cmp 0x10\(%r14\),%rsp", "the stack guard compare")
    lcc = expect(dirs, 3, r"jbe (\S+)", "jbe <morestack label>").group(1)
    expect(dirs, 4, r"push %rbp", "push %rbp")
    expect(dirs, 5, r"mov %rsp,%rbp", "mov %rsp,%rbp")
    fs = int(expect(dirs, 6, rf"sub \$({HEX}),%rsp", "sub $fs,%rsp").group(1), 16)
    dsp = int(expect(dirs, 7, rf"mov %rbx,({HEX})\(%rsp\)", "the rbx spill").group(1), 16)
    if dsp != fs + 24:
        raise NoMatch(f"rbx spill at {dsp:#x}(%rsp) is not fs + 24 = {fs + 24:#x} (caller slot rsp + 16)")
    expect(dirs, 8, r"nop", "nop")
    expect(dirs, 9, r"cmp \$0x8,%rcx", "cmp $0x8,%rcx")
    lbb = expect(dirs, 10, r"je (\S+)", "je <accept label>").group(1)
    jb = label_index(dirs, lbb)
    tail = [r"mov \(%rbx\),%rcx", r"nop", r"mov %rcx,\(%rax\)", r"xor %eax,%eax", r"xor %ebx,%ebx",
            rf"add \${fs:#x},%rsp", r"pop %rbp", r"retq"]
    for n, rx in enumerate(tail):
        expect(dirs, jb + 1 + n, rx, f"P1 tail directive {n + 1}")
    return dict(fn=fn, l0=l0, lcc=lcc, lbb=lbb, fs=fs, dsp=dsp, jb=jb)


def p1(args):
    dirs, sha = read_S(args.S)
    p = p1_read(dirs)
    c = args.const
    out = header(sha, args.S, args, f"; P1 parameters: frame {p['fs']:#x}, spill {p['dsp']:#x}, "
                 f"accept label at directive {p['jb']}")
    out += "set_option maxRecDepth 100000 in\n"
    out += P1_STMT.format(name=args.name, const=c)
    head = (f"E2eScal.u64DecHead {lean_str(p['fn'])} {lean_str(p['l0'])} {lean_str(p['lcc'])} "
            f"{lean_str(p['lbb'])} {p['fs']} {p['dsp']}")
    out += infix_have("hA", head, 0, c)
    out += infix_have("hB", f"E2eScal.u64DecTail {lean_str(p['lbb'])} {p['fs']}", p["jb"], c)
    out += label_have("hl", p["jb"], c)
    out += (f"  with_reducible exact (E2eScal.u64dec_accept _ _ _ _ {p['fs']} {p['dsp']} (by decide) k (k + {p['jb']})\n"
            f"    hA hB hl e8 he8 s ra guard fp s2 c0 hfp h2 hc0 R h_mem hguard hlen)\n")
    out += kind_thm(args.name, f"E2eScal.u64DecAcceptKind h {c}")
    if args.same_as:
        out += f"\n/-- Same proposition as the hand theorem. -/\ntheorem {args.name}_same : @{args.same_as} = @{args.name} := rfl\n"
    out += "\nend E2eScal.Gen\n"
    return out


# ---------------------------------------------------------------- P2 decode

# Audit AU-08: only the code hypotheses (k, hk, hf) are binders before the colon; the rest of the statement is one
# `∀ …, …` after it, and the proof is `exact E2eScal.rootdec_seg … hA hB hl` with NO further argument. This
# alone checks only the text after the colon (review fix-r1 M2: an added binder before the colon compiled).
# The full type, binders included, is checked by the `_kind` theorem emitted after it (`kind_thm`).
P2DEC_STMT = """theorem {name} (k : Nat) (hk : {const}.IsInfixAt Host.prog k) (hf : LabelsFresh {const} k) :
    ∀ (sp rcv bf aR aB aS aRet aLo aP aL aC aSrc : BitVec 64) (St : Nat)
    (hR : sp + ({dR} : Int64).toBitVec = aR) (hB' : sp + ({dB} : Int64).toBitVec = aB)
    (hS : sp + ({dS} : Int64).toBitVec = aS)
    (hRet : sp - 8 = aRet) (hLo : sp - 8 - BitVec.ofNat 64 St = aLo)
    (hP : rcv + ({fP} : Int64).toBitVec = aP) (hL : rcv + ({fL} : Int64).toBitVec = aL)
    (hC : rcv + ({fC} : Int64).toBitVec = aC)
    (hSrc : bf + ({src} : Int64).toBitVec = aSrc)
    (rbp0 r140 : UInt64) (root : List UInt8) (hroot : root.length = 32)
    (spl rslot lo lS vP vL vC : List UInt8)
    (hspl : spl.length = 24) (hrs : rslot.length = 8) (hlo : lo.length = St) (hlS : lS.length = 8)
    (hvP : vP.length = 8) (hvL : vL.length = 8) (hvC : vC.length = 8)
    (R : DataMem → Prop) (Heap : Nat → DataMem → Prop) (avail : Nat) (hav : 32 ≤ avail)
    (s : MachineData) (hrsp : s.regs.rsp = {{ toBitVec := sp }}) (hrbp : s.regs.rbp = rbp0)
    (hr14 : s.regs.r14 = r140)
    (h_mem : s.dmem =⋆ Eq ((Int.toBytes 8 rcv.toInt).At aR) ⋆ Eq ((Int.toBytes 8 bf.toInt).At aB)
      ⋆ Eq (spl.At sp) ⋆ Eq (rslot.At aRet) ⋆ Eq (lo.At aLo) ⋆ Eq (lS.At aS)
      ⋆ Heap avail
      ⋆ Eq (vP.At aP) ⋆ Eq (vL.At aL) ⋆ Eq (vC.At aC)
      ⋆ Eq (root.At aSrc)
      ⋆ Eq ([0, 0, 0, 0].At (label "runtime.writeBarrier").toBitVec) ⋆ R)
    (hms : MakesliceC Heap E2e.Data.e2eU8Type_addr 1 St) (hmm : MemmoveC St),
    Eventually (step1 Host.exe)
      (fun st => st.pc = Host.addrOf (k + {j2} + 12) ∧ st.data.regs.rsp = {{ toBitVec := sp }}
        ∧ st.data.regs.rbp = rbp0 ∧ st.data.regs.r14 = r140 ∧
        ∃ (p : BitVec 64) (spl' lo' : List UInt8), spl'.length = 24 ∧ lo'.length = St
          ∧ st.data.regs.rdx.toBitVec = rcv ∧
        (Eq ((Int.toBytes 8 rcv.toInt).At aR) ⋆ Eq ((Int.toBytes 8 bf.toInt).At aB)
          ⋆ Eq (spl'.At sp)
          ⋆ Eq ((Int.toBytes 8 (Host.addrOf (k + {j2} + 6 + 1)).toBitVec.toInt).At aRet)
          ⋆ Eq (lo'.At aLo)
          ⋆ Eq ((Int.toBytes 8 p.toInt).At aS)
          ⋆ Heap (avail - 32)
          ⋆ Eq ((Int.toBytes 8 p.toInt).At aP) ⋆ Eq ((Int.toBytes 8 32).At aL)
          ⋆ Eq ((Int.toBytes 8 32).At aC) ⋆ Eq (root.At p)
          ⋆ Eq (root.At aSrc)
          ⋆ Eq ([0, 0, 0, 0].At (label "runtime.writeBarrier").toBitVec) ⋆ R) st.data.dmem)
      ⟨s, Host.addrOf (k + {j1})⟩ := by
"""


def ir_roots(ir_path, tname):
    """(field name, SSZ offset, Go offset) of every 32-byte `[]byte` vector field of the container, from the
    IR. Only the requested type is read."""
    raw = pathlib.Path(ir_path).read_bytes()
    pkg, name = tname.rsplit(".", 1)
    ts = [t for c in json.loads(raw)["configs"] for t in c.get("types", [])
          if t.get("name") == name and t.get("package", "").endswith("/" + pkg)]
    if not ts:
        raise NoMatch(f"type {tname} not in the IR")
    t = ts[0]
    goff = {f["name"]: f["offset_gc_amd64"] for f in t["go_fields"]}
    roots, off = [], 0
    for f in t["ir"]["fields"]:
        v = f["v"]
        if v.get("variable"):
            raise NoMatch(f"field {f['key']} is variable-size (not a P2 container)")
        if v.get("k") == "vector" and v.get("size") == 32 and v.get("elem", {}).get("k") == "byte" \
                and v.get("go_type") == "[]byte":
            roots.append((f["key"], off, goff[f["key"]]))
        off += v["fixed_size"]
    return roots, hashlib.sha256(raw).hexdigest()


def p2dec_find(dirs, fo, src):
    """The decode segment of the field at Go offset `fo`, SSZ offset `src`: (j1, j2, params)."""
    hits = []
    for i in range(len(dirs)):
        if dirs[i] != "lea type__+387072(%rip),%rax":
            continue
        try:
            expect(dirs, i + 1, r"xor %ebx,%ebx", "xor %ebx,%ebx")
            expect(dirs, i + 2, r"mov \$0x20,%ecx", "mov $0x20,%ecx")
            expect(dirs, i + 3, r"callq runtime\.makeslice", "callq runtime.makeslice")
            dR = int(expect(dirs, i + 4, rf"mov ({HEX})\(%rsp\),%rdx", "the receiver reload").group(1), 16)
            fL = int(expect(dirs, i + 5, rf"movq \$0x0,({HEX})\(%rdx\)", "len = 0").group(1), 16)
            fC = int(expect(dirs, i + 6, rf"movq \$0x20,({HEX})\(%rdx\)", "cap = 32").group(1), 16)
        except NoMatch:
            continue
        if fL != fo + 8:
            continue
        if fC != fo + 16:
            raise NoMatch(f"directive {i + 6}: cap at {fC:#x}, expected {fo + 16:#x}")
        expect(dirs, i + 7, r"cmpl \$0x0,runtime\.writeBarrier\(%rip\)", "the write-barrier test")
        lff = expect(dirs, i + 8, r"je (\S+)", "je <no-barrier label>").group(1)
        j2 = label_index(dirs, lff)
        dS = int(expect(dirs, j2 + 1, rf"mov %rax,({HEX})\(%rsp\)", "the pointer save").group(1), 16)
        fP = int(expect(dirs, j2 + 2, rf"mov %rax,({HEX})\(%rdx\)", "the pointer store").group(1), 16)
        if fP != fo:
            raise NoMatch(f"directive {j2 + 2}: pointer at {fP:#x}, IR field offset {fo:#x}")
        dB = int(expect(dirs, j2 + 3, rf"mov ({HEX})\(%rsp\),%rbx", "the buffer reload").group(1), 16)
        s_ = int(expect(dirs, j2 + 4, rf"add \$({HEX}),%rbx", "add $src,%rbx").group(1), 16)
        if s_ != src:
            raise NoMatch(f"directive {j2 + 4}: source offset {s_:#x}, IR SSZ offset {src:#x}")
        expect(dirs, j2 + 5, r"mov \$0x20,%ecx", "mov $0x20,%ecx")
        expect(dirs, j2 + 6, r"callq runtime\.memmove", "callq runtime.memmove")
        if int(expect(dirs, j2 + 7, rf"mov ({HEX})\(%rsp\),%rdx", "the receiver reload").group(1), 16) != dR:
            raise NoMatch(f"directive {j2 + 7}: receiver reload differs from {dR:#x}")
        expect(dirs, j2 + 8, rf"movq \$0x20,{fL:#x}\(%rdx\)", "len = 32")
        expect(dirs, j2 + 9, rf"movq \$0x20,{fC:#x}\(%rdx\)", "cap = 32")
        expect(dirs, j2 + 10, r"cmpl \$0x0,runtime\.writeBarrier\(%rip\)", "the write-barrier test")
        lwb = expect(dirs, j2 + 11, r"jne (\S+)", "jne <barrier label>").group(1)
        hits.append((i, j2, dict(lff=lff, lwb=lwb, dR=dR, dB=dB, dS=dS, fP=fP, fL=fL, fC=fC, src=src)))
    if len(hits) != 1:
        raise NoMatch(f"field at Go offset {fo:#x}: {len(hits)} decode segments match (expected 1)")
    return hits[0]


def p2dec(args):
    dirs, sha = read_S(args.S)
    roots, irsha = ir_roots(args.ir, args.type)
    if not roots:
        raise NoMatch(f"{args.type}: no 32-byte field")
    c = args.const
    out = header(sha, args.S, args, f" and `{args.ir}` (sha256 `{irsha}`, type `{args.type}`)")
    for (fname, src, fo) in roots:
        j1, j2, p = p2dec_find(dirs, fo, src)
        name = f"{args.prefix}_{fname}_seg"
        out += "set_option maxHeartbeats 16000000 in\nset_option maxRecDepth 100000 in\n"
        out += f"/-- `{fname}` (SSZ offset {src}, Go offset {fo}): decode segment, directives {j1}–{j2 + 11}. -/\n"
        out += P2DEC_STMT.format(name=name, const=c, j1=j1, j2=j2, **p)
        out += infix_have("hA", f"E2eScal.rootDecHead {lean_str(p['lff'])} {p['dR']} {p['fL']} {p['fC']}", j1, c)
        out += infix_have("hB", f"E2eScal.rootDecMid {lean_str(p['lff'])} {lean_str(p['lwb'])} {p['dR']} {p['dB']} "
                          f"{p['dS']} {p['fP']} {p['fL']} {p['fC']} {p['src']}", j2, c)
        out += label_have("hl", j2, c)
        # the lemma instance closes the whole `∀` goal after the colon, no argument after hl
        out += f"  with_reducible exact E2eScal.rootdec_seg _ _ _ _ _ _ _ _ _ (k + {j1}) (k + {j2}) hA hB hl\n"
        out += kind_thm(name, f"E2eScal.rootDecSegKind h {c} {j1} {j2} {p['dR']} {p['dB']} {p['dS']} {p['fP']} "
                              f"{p['fL']} {p['fC']} {p['src']}") + "\n"
    out += "end E2eScal.Gen\n"
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("mode", choices=["p1", "p2dec"])
    ap.add_argument("--S", required=True)
    ap.add_argument("--const", required=True)
    ap.add_argument("--name")
    ap.add_argument("--same-as")
    ap.add_argument("--ir")
    ap.add_argument("--type")
    ap.add_argument("--prefix")
    ap.add_argument("--imports", required=True)
    ap.add_argument("--open", default="")
    args = ap.parse_args()
    try:
        out = p1(args) if args.mode == "p1" else p2dec(args)
    except NoMatch as e:
        print(f"scalgen {args.mode}: no template match: {e}", file=sys.stderr)
        sys.exit(2)
    sys.stdout.write(out)


if __name__ == "__main__":
    main()
