def _vadd(v, x):
    """Value `v` plus the constant `x` (a pointer plus an offset stays that pointer)."""
    if v[0] in ("RCV", "BF"):
        return (v[0], v[1] + x)
    if v[0] == "IMM":
        return ("IMM", (v[1] + x) % (1 << 64))
    return ("UNK",)


