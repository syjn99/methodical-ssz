    L.append(f"    (hguard : guard.toNat < s.regs.rsp.toNat) (hlen : s.regs.rcx = {ssz}) (hav : {total} ≤ avail)")
    L.append("    (hms : MakesliceC Heap E2e.Data.e2eU8Type_addr 1 S) (hmm : MemmoveC S) :")
