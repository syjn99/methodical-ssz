# the statement of the call block (`Codec.call_decode_segment`); `STEP_CALL_STATEMENT` is its window form
CALL_DECODE_STATEMENT = """theorem {name} (k : Nat) (hk : {const}.IsInfixAt Host.prog k) (hf : LabelsFresh {const} k) :
    ∀ (hC : Uint64CalleeAccept "{fn}")
    (sp dst src aRet aFp aS2 : BitVec 64)
    (hRet : sp - 8 = aRet) (hFp : sp - 16 = aFp) (hS2 : sp + 8 = aS2)
    (rbp0 r140 guard : UInt64) (e8 rslot fp s2 c0 : List UInt8)
    (he8 : e8.length = 8) (hrs : rslot.length = 8) (hfp : fp.length = 8) (hs2 : s2.length = 8)
    (hc0 : c0.length = 8) (hguard : guard.toNat < aRet.toNat)
    (F : DataMem → Prop)
    (s : MachineData) (hrsp : s.regs.rsp = {{ toBitVec := sp }}) (hrbp : s.regs.rbp = rbp0)
    (hr14 : s.regs.r14 = r140) (hrax : s.regs.rax.toBitVec = dst) (hrbx : s.regs.rbx.toBitVec = src)
    (hrcx : s.regs.rcx = 8)
    (h_mem : s.dmem =⋆ Eq (rslot.At aRet) ⋆ Eq (fp.At aFp) ⋆ Eq (s2.At aS2)
      ⋆ Eq ((Int.toBytes 8 guard.toBitVec.toInt).At (r140.toBitVec + 16))
      ⋆ Eq (e8.At src) ⋆ Eq (c0.At dst) ⋆ F),
    Eventually (step1 Host.exe)
      (fun st => st.pc = Host.addrOf (k + {j2} + 1) ∧ st.data.regs.rax = 0 ∧ st.data.regs.rbx = 0
        ∧ st.data.regs.rsp = {{ toBitVec := sp }} ∧ st.data.regs.rbp = rbp0 ∧ st.data.regs.r14 = r140 ∧
        (Eq ((Int.toBytes 8 (Host.addrOf (k + {j} + 1)).toBitVec.toInt).At aRet)
          ⋆ Eq ((Int.toBytes 8 rbp0.toBitVec.toInt).At aFp) ⋆ Eq ((Int.toBytes 8 src.toInt).At aS2)
          ⋆ Eq ((Int.toBytes 8 guard.toBitVec.toInt).At (r140.toBitVec + 16))
          ⋆ Eq (e8.At src) ⋆ Eq (e8.At dst) ⋆ F) st.data.dmem)
      ⟨s, Host.addrOf (k + {j})⟩ := by
"""


# ---------------------------------------------------------------- step chain (front end of `decoder --whole-accept`)
#
# Lemmas: `lean/Codec/NopWindow.lean`, `lean/Codec/WindowSteps.lean`,
# `lean/Codec/Kind/WindowSteps.lean`, `lean/Codec/Kind/CalleeDecodeWindow.lean`, `lean/Codec/Kind/FixedBytesDecodeWindow.lean`, `lean/Codec/Kind/FixedBytesDecodeWindowOffsetZero.lean`; the interface is the step lemmas.
# Matching is NOT by multi-directive set-up templates. The generator walks the accept path of the decoder from the
# end of the head (prologue, spills, nil check) and keeps a small DATAFLOW state: which register / stack slot holds
# the receiver (`rcv + o`), the buffer (`bf + o`), an immediate, the bytes of the buffer at an offset, the new slice
# pointer of a byte field, or something unknown. Each directive is one of:
#   * a step form with a kinded step lemma (`mov %rS,%rD`, `mov d(%rB),%rD`, `mov %rS,d(%rB)`, `lea d(%rB),%rD`,
#     `add $i,%rD`, `mov $i,%eD`, `jmp l`, `l:`): one theorem `<prefix>_directive_<index>` + `_kind` per directive;
#   * `nop`: nothing is emitted; the nop is a leading nop of the next window;
#   * `callq <callee with a proved spec>`: the call block window `nop* callq nop* test nop* je lok` (`call_decode_segment_window`,
#     kind `callDecodeSegmentKindWindow`), emitted ONLY when the dataflow shows rax = rcv + (IR Go offset), rbx = bf + (IR SSZ
#     offset), rcx = 8 and the IR field is the next one;
#   * `lea type__+387072(%rip),%rax`: the byte segment over two windows (`bytes_decode_segment_window` / `bytes_decode_segment_offset_zero_window`,
#     kinds `bytesDecodeSegmentKindWindow` / `bytesDecodeSegmentOffsetZeroKindWindow`), emitted ONLY when the receiver / buffer reload slots hold
#     the receiver / buffer, the registers are in the lemma's sets, n in {20, 32, 48, 96}, the displacements equal the IR;
#     for n = 4 the inline-copy segment over three windows (`bytes_decode_inline_segment_window`, kind
#     `bytesDecodeInlineSegmentKindWindow`): no memmove, `mov src(%rB),%eT; mov %eT,(%rax)`, `je` over the write
#     barrier, the pointer store after it; the field is complete at the end of the segment;
#   * anything else (another mnemonic or width, an index / rip operand, an immediate store, a callee without a proved
#     spec, a conditional branch): the walk stops; every field not yet complete is "not covered: <reason>".
# A field is complete at its own event: the call block (callee field), the store of the bytes `bf + src` into
# `rcv + f` (uint64 field), the store of the new slice pointer into `rcv + fP` after the byte segment (byte field).
# Its theorems are the steps / blocks since the previous field. Events out of IR order stop the walk.
# Not emitted (no kind in the hand-written lemmas): the head (`decpro_seg`, spills, `step_nil_check`), the epilogue
# (`decret_seg`), field compositions. `--whole-accept` adds the head, the epilogue and the accept theorem.
# The dataflow is the generator's acceptance rule only; it is not trusted. Lean checks every emitted theorem
# (`he` by `rfl` on the code constant) and its `_kind` line; a field composition that uses the steps re-checks the
# entry state of each block (`rfl` / `ecancel`).

STEP_R64 = ("rax", "rbx", "rcx", "rdx", "rsi", "rdi", "rsp", "rbp", "r8", "r9", "r10", "r11", "r12", "r13", "r14", "r15")
STEP_R32 = {"eax": "rax", "ebx": "rbx", "ecx": "rcx", "edx": "rdx", "esi": "rsi", "edi": "rdi",
          **{f"r{i}d": f"r{i}" for i in range(8, 16)}}
STEP_RX = ("rdx", "rsi")                              # bytesdec_seg_window: receiver register before the copy
STEP_RY = ("rax", "rcx", "rdx", "rsi", "rdi")          # ... and after it
STEP_HX = {"rdx": "Or.inl rfl", "rsi": "Or.inr rfl"}
STEP_HY = {"rax": "Or.inl rfl", "rcx": "Or.inr (Or.inl rfl)", "rdx": "Or.inr (Or.inr (Or.inl rfl))",
         "rsi": "Or.inr (Or.inr (Or.inr (Or.inl rfl)))", "rdi": "Or.inr (Or.inr (Or.inr (Or.inr rfl)))"}
# bytes_decode_inline_segment_window: the receiver register, and the (buffer, temporary) register pairs
STEP_INLINE_RX = ("rdx",)
STEP_INLINE_BT = {("rsi", "rdi"): "Or.inl ⟨rfl, rfl⟩", ("rbx", "rsi"): "Or.inr ⟨rfl, rfl⟩"}
STEP_OPTS = "set_option maxHeartbeats 4000000 in\nset_option maxRecDepth 100000 in\n"
STEP_SEGMENT_OPTIONS = "set_option maxHeartbeats 16000000 in\nset_option maxRecDepth 100000 in\n"


class StepStop(Exception):
    """The walk stops at directive `at`: `why` (miss class `cls`)."""

    def __init__(self, at, why, cls):
        super().__init__(why)
        self.at, self.why, self.cls = at, why, cls


def _step_disp(s):
    return 0 if s in (None, "") else _hexs(s)


def step_parse(d):
    """One directive -> a tuple: ("nop",), ("label", l), ("movrr", rD, rS), ("ld", rD, rB, disp), ("st", rS, rB, disp),
    ("lea", rD, rB, disp), ("add", rD, imm), ("movi", rD, imm), ("jmp", l), ("call", fn), ("lea_mk",) for the
    makeslice type operand, or ("other", text). Only 64-bit registers in the register / memory forms."""
    if d == "nop":
        return ("nop",)
    if label_of(d) is not None:
        return ("label", label_of(d))
    R = "|".join(STEP_R64)
    m = re.fullmatch(rf"mov %({R}),%({R})", d)
    if m:
        return ("movrr", m.group(2), m.group(1))
    m = re.fullmatch(rf"mov ({SHX})?\(%({R})\),%({R})", d)
    if m:
        return ("ld", m.group(3), m.group(2), _step_disp(m.group(1)))
    m = re.fullmatch(rf"mov %({R}),({SHX})?\(%({R})\)", d)
    if m:
        return ("st", m.group(1), m.group(3), _step_disp(m.group(2)))
    m = re.fullmatch(rf"lea ({SHX})?\(%({R})\),%({R})", d)
    if m:
        return ("lea", m.group(3), m.group(2), _step_disp(m.group(1)))
    m = re.fullmatch(rf"add \$({SHX}),%({R})", d)
    if m:
        return ("add", m.group(2), _hexs(m.group(1)))
    m = re.fullmatch(rf"mov \$({SHX}),%({'|'.join(STEP_R32)})", d)
    if m:
        return ("movi", STEP_R32[m.group(2)], _hexs(m.group(1)))
    m = re.fullmatch(r"jmp (\S+)", d)
    if m:
        return ("jmp", m.group(1))
    m = re.fullmatch(r"callq (\S+)", d)
    if m:
        return ("call", m.group(1))
    if d == "lea type__+387072(%rip),%rax":
        return ("lea_mk",)
    if d in NESTED_TYPE_LEA.values():
        return ("lea_new", d)
    return ("other", d)


def _i64(x):
    """Int64 literal in a statement: `(120 : Int64)` / `((-40) : Int64)`."""
    return f"(({x}) : Int64)" if x < 0 else f"({x} : Int64)"


def _vadd(v, x):
    """Value `v` plus the constant `x` (a pointer plus an offset stays that pointer)."""
    if v[0] in ("RCV", "BF"):
        return (v[0], v[1] + x)
    if v[0] == "IMM":
        return ("IMM", (v[1] + x) % (1 << 64))
    return ("UNK",)


def _vstr(v):
    return {"RCV": lambda: f"rcv{v[1]:+d}", "BF": lambda: f"bf{v[1]:+d}", "IMM": lambda: f"{v[1]:#x}",
            "MEM": lambda: f"bytes(bf{v[1]:+d})", "PTR": lambda: f"ptr({v[1]})", "CAP": lambda: "cap",
            "LEN": lambda: "len", "UNK": lambda: "unknown"}.get(v[0], lambda: str(v))()


STEP_HEAD_SPILL = {"rax": ("RCV", 0), "rbx": ("BF", 0), "rcx": ("LEN",), "rdi": ("CAP",)}


class StepEpilogueMiss(StepStop):
    """Every field is complete but the directives after the last field event are not the plain return."""


class StepHeadMiss(NoMatch):
    """The head is not the covered prologue (exit 2); `cls` is the miss class reported for every field."""

    def __init__(self, why, cls):
        super().__init__(why)
        self.why, self.cls = why, cls


# The prologue forms of `decoderPrologue` (`Codec/DecoderPrologue.lean`, lemma `decpro_seg`), directives 2–10 with the nops erased
STEP_PRO = [r"cmp 0x10\(%r14\),%rsp", r"jbe \S+", r"push %rbp", r"mov %rsp,%rbp", r"sub \$(0x[0-9a-f]+),%rsp",
          r"mov %rbx,(0x[0-9a-f]+)\(%rsp\)", r"cmp \$(0x[0-9a-f]+),%rcx", r"jne \S+"]


def step_slot_ok(d, F):
    """Stack-store rule: an 8-byte store `mov %r,d(%rsp)` is modelled only when `d` is a multiple
    of 8 and lies in the frame `[0, F)` or in the caller's argument spill area `[F + 16, F + 48)` (rax, rbx, rcx,
    rdi of the decoder's arguments). `[F, F + 16)` holds the saved rbp and the return address; everything else is
    outside what the walk models. With every tracked slot aligned, two slots overlap only when they are equal."""
    return d % 8 == 0 and (0 <= d < F or F + 16 <= d < F + 48)


def step_head(dirs, ssz_size):
    """The decoder head: directives 0–10 must be the `decoderPrologue` prologue of `decode_prologue_segment` (two labels; directives 2–8
    the six instructions `cmp 0x10(%r14),%rsp; jbe; push %rbp; mov %rsp,%rbp; sub $F,%rsp; mov %rbx,dB(%rsp)` in
    this order and one `nop`; directives 9–10 `cmp $size,%rcx; jne <size error>`), then the spills `mov %r,d(%rsp)`
    of the argument registers rax / rbx / rcx / rdi (after the frame is set up; each under the stack-store rule),
    then an optional `test %al,(%rax)`. Returns (index after the head, slots, F); a mismatch raises StepHeadMiss
    (class `padding` when the head matches with its nops erased but not at the fixed positions, else `other`).
    The immediate of `cmp $size,%rcx` must equal `ssz_size`, the IR SSZ fixed size of the type; else StepHeadMiss,
    class `other`."""
    if len(dirs) < 12 or label_of(dirs[0]) is None or label_of(dirs[1]) is None:
        raise StepHeadMiss("step head: directives 0, 1 are not the two function labels", "other")
    win = [d for d in dirs[2:9] if d != "nop"]
    ok = (len(win) == 6 and all(re.fullmatch(rx, d) for rx, d in zip(STEP_PRO[:6], win))
          and re.fullmatch(STEP_PRO[6], dirs[9]) and re.fullmatch(STEP_PRO[7], dirs[10]))
    if not ok:
        rest = [d for d in dirs[2:] if d != "nop"][:8]
        shifted = len(rest) == 8 and all(re.fullmatch(rx, d) for rx, d in zip(STEP_PRO, rest))
        raise StepHeadMiss("step head: directives 2–10 are not the prologue of `decode_prologue_segment` (`cmp 0x10(%r14),%rsp; jbe; "
                         "push %rbp; mov %rsp,%rbp; sub $F,%rsp; mov %rbx,dB(%rsp)` and one `nop` in 2–8, `cmp $size,%rcx; "
                         "jne` at 9–10)" + ("; it matches with the nops erased: a `nop` moves the fixed head positions"
                                            if shifted else ""), "padding" if shifted else "other")
    size = int(re.fullmatch(STEP_PRO[6], dirs[9]).group(1), 16)
    if size != ssz_size:
        raise StepHeadMiss(f"step head: directive 9 `{dirs[9]}`: size immediate {size:#x}, IR SSZ fixed size "
                         f"{ssz_size:#x}", "other")
    F = int(re.fullmatch(STEP_PRO[4], win[4]).group(1), 16)
    dB = int(re.fullmatch(STEP_PRO[5], win[5]).group(1), 16)
    if F % 8 or not step_slot_ok(dB, F):
        raise StepHeadMiss(f"step head: frame size {F:#x} / rbx spill at {dB:#x} outside the stack-store rule", "other")
    slots = {dB: STEP_HEAD_SPILL["rbx"]}
    i = 11
    while i < len(dirs):
        m = re.fullmatch(r"mov %(rax|rbx|rcx|rdi),(0x[0-9a-f]+)\(%rsp\)", dirs[i])
        if not m:
            break
        d = int(m.group(2), 16)
        if not step_slot_ok(d, F):
            raise StepHeadMiss(f"step head: directive {i} `{dirs[i]}`: spill displacement {d:#x} outside the stack-store "
                             f"rule (multiple of 8, in [0, {F:#x}) or [{F + 16:#x}, {F + 48:#x}))", "other")
        slots[d] = STEP_HEAD_SPILL[m.group(1)]
        i += 1
    if i < len(dirs) and dirs[i] == "test %al,(%rax)":
        i += 1
    return i, slots, F


def step_label_index(dirs, l, at):
    try:
        return label_index(dirs, l)
    except NoMatch:
        raise StepStop(at, f"label {l} not found", "other")


def step_window(dirs, a, pattern, at, what):
    """Window from `a`: the non-nop directives must be `len(pattern)` items matched by the regular expressions in
    `pattern`, nops anywhere between (none after the last); no label inside except where the pattern has one.
    Returns (end index, list of match objects, list of indices of the non-nop directives)."""
    ms, idx, i = [], [], a
    for rx in pattern:
        while i < len(dirs) and dirs[i] == "nop":
            i += 1
        if i >= len(dirs):
            raise StepStop(at, f"{what}: end of file, expected /{rx}/", "other")
        m = re.fullmatch(rx, dirs[i])
        if not m:
            cls = "new directive form" if label_of(dirs[i]) is None else "other"
            if label_of(dirs[i]) is not None:
                raise StepStop(i, f"{what}: label `{dirs[i]}` inside the window (directive {i})", "other")
            raise StepStop(i, f"{what}: directive {i} `{dirs[i]}` is not /{rx}/", cls)
        ms.append(m)
        idx.append(i)
        i += 1
    return i, ms, idx


class StepState:
    def __init__(self, slots):
        self.r = {r: ("UNK",) for r in STEP_R64}
        self.r.update(rax=("RCV", 0), rbx=("BF", 0), rcx=("LEN",), rdi=("CAP",))
        self.slot = dict(slots)

    def clobber(self, keep=()):
        for r in STEP_R64:
            if r not in ("rsp", "rbp", "r14") and r not in keep:
                self.r[r] = ("UNK",)


def step_inline(dirs, st, f, F, i, a, endA, mA, iA, jl, unit):
    """The 4-byte inline-copy segment (`bytes_decode_inline_segment_window`) after its head window `mA` (from `a` to
    `endA`, `je lff` with `lff` at `jl`): the middle window `lff: mov %rax,fP(%rX); mov dB(%rsp),%rB; mov src(%rB),%eT;
    mov %eT,(%rax); movq $4,fL(%rX); movq $4,fC(%rX); cmpl $0x0,runtime.writeBarrier(%rip); je lwb` and the tail window
    `lwb: mov %rax,fP(%rX)`. Fills `unit` and the dataflow state; any mismatch raises StepStop."""
    name, src, fo = f[0], f[1], f[2]
    r32 = "|".join(k for k in STEP_R32 if not k.startswith("r"))
    pat = [re.escape(f"{dirs[jl]}"), rf"mov %rax,({SHX})?\(%(\w+)\)", rf"mov ({SHX})\(%rsp\),%(\w+)",
           rf"mov ({SHX})?\(%(\w+)\),%({r32})", rf"mov %({r32}),\(%rax\)",
           rf"movq \$({SHX}),({SHX})?\(%(\w+)\)", rf"movq \$({SHX}),({SHX})?\(%(\w+)\)",
           r"cmpl \$0x0,runtime\.writeBarrier\(%rip\)", r"je (\S+)"]
    if label_of(dirs[jl]) is None:
        raise StepStop(i, f"inline byte segment at {i}: directive {jl} is not the label of the head jump", "other")
    endB, mB, iB = step_window(dirs, jl, pat, jl, f"inline byte segment middle at {jl}")
    lwb = mB[8].group(1)
    jw = step_label_index(dirs, lwb, i)
    endC, mC, iC = step_window(dirs, jw, [re.escape(f"{lwb}:"), rf"mov %rax,({SHX})?\(%(\w+)\)"], jw,
                               f"inline byte segment tail at {jw}")
    sz, dR, rX = _hexs(mA[2].group(1)), _hexs(mA[4].group(1)), mA[4].group(2)
    fL, fC = _step_disp(mA[5].group(1)), _step_disp(mA[6].group(2))
    fP, rX2, dB, rB = _step_disp(mB[1].group(1)), mB[1].group(2), _hexs(mB[2].group(1)), mB[2].group(2)
    src_, rB2, rT = _step_disp(mB[3].group(1)), mB[3].group(2), STEP_R32[mB[3].group(3)]
    rT2 = STEP_R32[mB[4].group(1)]
    l1, fL2, rX3 = _hexs(mB[5].group(1)), _step_disp(mB[5].group(2)), mB[5].group(3)
    c1, fC2, rX4 = _hexs(mB[6].group(1)), _step_disp(mB[6].group(2)), mB[6].group(3)
    fP2, rX5 = _step_disp(mC[1].group(1)), mC[1].group(2)
    checks = [
        (sz == FIELD_INLINE_SIZE and _hexs(mA[6].group(1)) == FIELD_INLINE_SIZE and l1 == FIELD_INLINE_SIZE
         and c1 == FIELD_INLINE_SIZE, f"size immediates {sz:#x} / {l1:#x} / {c1:#x}, inline size {FIELD_INLINE_SIZE}",
         "other"),
        (len({rX, mA[5].group(2), mA[6].group(3), rX2, rX3, rX4, rX5}) == 1,
         f"receiver register not the same in its seven uses ({rX}, {mA[5].group(2)}, {mA[6].group(3)}, {rX2}, {rX3}, "
         f"{rX4}, {rX5})", "register"),
        (rX in STEP_INLINE_RX, f"receiver register {rX} (lemma: {', '.join(STEP_INLINE_RX)})", "register"),
        (rB2 == rB and rT2 == rT, f"copy registers: buffer {rB} / {rB2}, temporary {rT} / {rT2}", "register"),
        ((rB, rT) in STEP_INLINE_BT, f"buffer / temporary registers {rB} / {rT} (lemma: "
         f"{', '.join('/'.join(x) for x in STEP_INLINE_BT)})", "register"),
        (jw >= endB, f"write-barrier label {lwb} at {jw} not after the middle window", "other"),
        (fP == fo and fP2 == fo, f"pointer stores at Go offsets {fP} / {fP2}, IR Go offset {fo}", "other"),
        (fL == fP + 8 and fL2 == fL and fC == fP + 16 and fC2 == fC,
         f"len / cap stores at {fL} / {fC} (and {fL2} / {fC2}), pointer at {fP}", "other"),
        (src_ == src, f"source offset {src_}, IR SSZ offset {src}", "other"),
        (st.slot.get(dR) == ("RCV", 0), f"slot {dR:#x} (receiver reload) holds {_vstr(st.slot.get(dR, ('UNK',)))}, "
         f"not the receiver", "register"),
        (st.slot.get(dB) == ("BF", 0), f"slot {dB:#x} (buffer reload) holds {_vstr(st.slot.get(dB, ('UNK',)))}, "
         f"not the buffer", "register"),
        (min(dR, dB) >= 0x18, f"a slot below rsp + 0x18 (the makeslice argument area): {dR:#x}, {dB:#x}", "other"),
    ]
    for ok, why, c in checks:
        if not ok:
            raise StepStop(i, f"inline byte segment at {i} ({name}): {why}", c)
    unit.update(kind="inline", n=FIELD_INLINE_SIZE, rX=rX, rB=rB, rT=rT, j1=a, nA=endA - a, j2=jl, nB=endB - jl,
                j3=jw, nC=endC - jw, jc=iA[3], e=endC, lff=label_of(dirs[jl]), lwb=lwb, dR=dR, dB=dB, fP=fP, fL=fL,
                fC=fC, src=src_)
    st.clobber(keep=())
    st.r[rX] = ("RCV", 0)
    st.r[rB] = ("BF", 0)
    for x in list(st.slot):
        if x < 0x18:
            st.slot[x] = ("UNK",)


def step_nested(dirs, st, f, cls, info, F, i, a, lea, unit):
    """The nested Checkpoint block (`nested_checkpoint_decode_window`) at `a` (`lea` at `i`): the window
    `lea type(%rip),%rax; callq runtime.newobject; cmpl $0x0,runtime.writeBarrier(%rip); jne lwb; mov dR(%rsp),%rdx; jmp lst`,
    the window `lst: mov %rax,fP(%rdx); mov dB(%rsp),%rbx; add $src,%rbx; mov dC(%rsp),%rdi; add $rest,%rdi;
    mov $0x28,%ecx; callq fn; test %rax,%rax; je lok` and the label `lok`. The write-barrier path at `lwb` is not walked.
    Fills `unit` and the dataflow state; any mismatch raises StepStop."""
    name, src, fo = f[0], f[1], f[2]
    if cls != "nested":
        raise StepStop(i, f"directive {i} `{lea}`: nested object, the next IR field is {name} ({cls})",
                       "set-up order" if cls != "none" else "new field kind")
    tname = [n for n, fn in NESTED_CALLEES.items() if fn == info][0]
    if lea != NESTED_TYPE_LEA[tname]:
        raise StepStop(i, f"nested block at {i} ({name}): `{lea}` is not the type word of {tname}", "other")
    endA, mA, iA = step_window(dirs, a, [re.escape(lea), r"callq runtime\.newobject",
                                         r"cmpl \$0x0,runtime\.writeBarrier\(%rip\)", r"jne (\S+)",
                                         rf"mov ({SHX})\(%rsp\),%rdx", r"jmp (\S+)"], i, f"nested block head at {i}")
    lwb, dR, lst = mA[3].group(1), _hexs(mA[4].group(1)), mA[5].group(1)
    jw = step_label_index(dirs, lwb, i)
    jl = step_label_index(dirs, lst, i)
    if jl < endA or jw < endA:
        raise StepStop(i, f"nested block at {i}: label {lst} or {lwb} not after the head window", "other")
    pat = [re.escape(f"{lst}:"), rf"mov %rax,({SHX})?\(%rdx\)", rf"mov ({SHX})\(%rsp\),%rbx", rf"add \$({SHX}),%rbx",
           rf"mov ({SHX})\(%rsp\),%rdi", rf"add \$({SHX}),%rdi", rf"mov \$({SHX}),%ecx", r"callq (\S+)",
           r"test %rax,%rax", r"je (\S+)"]
    endB, mB, iB = step_window(dirs, jl, pat, jl, f"nested block call at {jl}")
    fP, dB, src_ = _step_disp(mB[1].group(1)), _hexs(mB[2].group(1)), _hexs(mB[3].group(1))
    dC, rest, sz, fn, lok = _hexs(mB[4].group(1)), _hexs(mB[5].group(1)), _hexs(mB[6].group(1)), mB[7].group(1), mB[9].group(1)
    j3 = step_label_index(dirs, lok, jl)
    checks = [
        (fn == info, f"callee {fn}, IR callee {info}", "other"),
        (sz == NESTED_SIZE[tname], f"size immediate {sz:#x}, SSZ size of {tname} {NESTED_SIZE[tname]:#x}", "other"),
        (fP == fo, f"pointer store at Go offset {fP}, IR Go offset {fo}", "other"),
        (src_ == src, f"source offset {src_}, IR SSZ offset {src}", "other"),
        (rest == -src, f"length adjustment {rest}, expected {-src}", "other"),
        (j3 >= endB, f"continuation label {lok} at {j3} not after the call window", "other"),
        (st.slot.get(dR) == ("RCV", 0), f"slot {dR:#x} (receiver reload) holds {_vstr(st.slot.get(dR, ('UNK',)))}, "
         f"not the receiver", "register"),
        (st.slot.get(dB) == ("BF", 0), f"slot {dB:#x} (buffer reload) holds {_vstr(st.slot.get(dB, ('UNK',)))}, "
         f"not the buffer", "register"),
        (st.slot.get(dC) == ("CAP",), f"slot {dC:#x} (capacity reload) holds {_vstr(st.slot.get(dC, ('UNK',)))}, "
         f"not the buffer capacity", "register"),
        (min(dR, dB, dC) >= 0x18, f"a slot below rsp + 0x18 (the spill area of the callees): {dR:#x}, {dB:#x}, {dC:#x}",
         "other"),
    ]
    for ok, why, c in checks:
        if not ok:
            raise StepStop(i, f"nested block at {i} ({name}): {why}", c)
    unit.update(kind="nested", fn=fn, lwb=lwb, lst=lst, lok=lok, dR=dR, fP=fP, dB=dB, src=src_, dC=dC, rest=rest,
                j1=a, nA=endA - a, j2=jl, nB=endB - jl, jc=iB[7], j3=j3, e=j3 + 1)
    st.clobber()
    st.r["rax"], st.r["rbx"] = ("IMM", 0), ("IMM", 0)
    # the block writes sp (the object pointer) and sp + 8 (the callee's spill of rbx) of the frame
    for x in list(st.slot):
        if x < 0x10:
            st.slot[x] = ("UNK",)
    st.slot[8] = ("BF", src)


def step_walk(dirs, fields, head_end, slots0, F):
    """The dataflow walk. Returns (done, stop, end): done = list of (field index, [emitted units]) for the complete
    fields in IR order; stop = None or the StepStop that ended the walk; end = the directive after the last field
    event (None after a stop). A unit is a dict with `kind` and parameters. Any other exception propagates
    (`decoder_step` maps it to exit 2)."""
    done = []
    try:
        end = _step_walk(dirs, fields, head_end, slots0, F, done)
    except StepStop as e:
        return done, e, None
    return done, None, end


def _step_walk(dirs, fields, head_end, slots0, F, done):
    st = StepState(slots0)

    def stack_store(d, v, at, text):
        """`mov %r,d(%rsp)`: stop unless `d` passes the stack-store rule; else every tracked slot the 8
        bytes at `d` overlap is invalidated (with aligned slots: only `d` itself) and `d` holds `v`."""
        if not step_slot_ok(d, F):
            raise StepStop(at, f"directive {at} `{text}`: 8-byte stack store at {d:#x} outside the stack-store rule "
                             f"(multiple of 8, in [0, {F:#x}) or [{F + 16:#x}, {F + 48:#x}))", "other")
        for x in list(st.slot):
            if x != d and abs(x - d) < 8:
                st.slot[x] = ("UNK",)
        st.slot[d] = v

    def no_frame_write(rD, at, text):
        """rbp (frame pointer) and r14 (goroutine pointer, stack guard at r14 + 16) are part of the block entry
        states (rbp0, r140); a write to them stops the walk."""
        if rD in ("rbp", "r14"):
            raise StepStop(at, f"directive {at} `{text}` writes {rD} (frame / goroutine register)", "other")
    cur, pend = 0, []
    seg_open = None              # byte field whose segment is emitted and whose pointer tail is pending
    i, a = head_end, head_end    # i: next directive; a: start of the next window (leading nops)
    seen = set()
    nf = len(fields)

    def fld():
        return fields[cur]

    def complete(unit=None):
        nonlocal cur, pend
        if unit:
            pend.append(unit)
        done.append((cur, pend))
        cur, pend = cur + 1, []

    def ir_event(fo_hit, what, at):
        """A receiver write at Go offset fo_hit that is an IR field other than the current one: order error."""
        for x, f in enumerate(fields):
            if f[2] == fo_hit and x != cur:
                raise StepStop(at, f"{what} writes field {f[0]} (Go offset {fo_hit}) while field {fields[cur][0]} is "
                                 f"the next in IR order", "set-up order")

    while cur < nf:
        if i >= len(dirs):
            raise StepStop(i, "end of file before every field was complete", "other")
        if i in seen:
            raise StepStop(i, f"directive {i} reached twice (loop)", "other")
        seen.add(i)
        d = dirs[i]
        op = step_parse(d)
        k = op[0]
        name, cls, info = fld()[0], fld()[3], fld()[4]
        if k == "nop":
            i += 1
            continue
        if seg_open is not None and k in ("call", "lea_mk", "lea_new"):
            raise StepStop(i, f"block at {i} before the pointer store of byte field {fields[seg_open][0]}", "set-up order")
        unit = dict(kind=k, j=a, e=i + 1, jd=i, text=d)
        if k == "label":
            unit.update(l=op[1])
            pend.append(unit)
        elif k == "jmp":
            jl = step_label_index(dirs, op[1], i)
            if jl <= i:
                raise StepStop(i, f"jmp {op[1]} backwards", "other")
            unit.update(l=op[1], jl=jl)
            pend.append(unit)
            i, a = jl, jl
            continue
        elif k == "movrr":
            rD, rS = op[1], op[2]
            if rD == "rsp" or rS == "rsp":
                raise StepStop(i, f"directive {i} `{d}` moves rsp (frame change)", "new directive form")
            no_frame_write(rD, i, d)
            unit.update(rD=rD, rS=rS)
            st.r[rD] = st.r[rS]
            pend.append(unit)
        elif k == "movi":
            rD, imm = op[1], op[2]
            no_frame_write(rD, i, d)
            unit.update(rD=rD, imm=imm)
            st.r[rD] = ("IMM", imm & 0xffffffff)
            pend.append(unit)
        elif k == "lea":
            rD, rB, disp = op[1], op[2], op[3]
            if rD == "rsp":
                raise StepStop(i, f"directive {i} `{d}` writes rsp", "new directive form")
            no_frame_write(rD, i, d)
            unit.update(rD=rD, rB=rB, disp=disp)
            st.r[rD] = ("UNK",) if rB == "rsp" else _vadd(st.r[rB], disp)
            pend.append(unit)
        elif k == "add":
            rD, imm = op[1], op[2]
            if rD == "rsp":
                raise StepStop(i, f"directive {i} `{d}` changes rsp (epilogue before every field was complete)", "other")
            no_frame_write(rD, i, d)
            unit.update(rD=rD, imm=imm)
            st.r[rD] = _vadd(st.r[rD], imm)
            pend.append(unit)
        elif k == "ld":
            rD, rB, disp = op[1], op[2], op[3]
            if rD == "rsp":
                raise StepStop(i, f"directive {i} `{d}` writes rsp", "new directive form")
            no_frame_write(rD, i, d)
            if rB == "rsp":
                v = st.slot.get(disp, ("UNK",))
            elif st.r[rB][0] == "BF":
                v = ("MEM", st.r[rB][1] + disp)
            elif st.r[rB][0] == "RCV":
                v = ("UNK",)
            else:
                raise StepStop(i, f"directive {i} `{d}`: load through {rB} = {_vstr(st.r[rB])} (unknown base)", "register")
            # value form for the words that blocks consume (receiver, buffer, slice pointer, an immediate), bytes form
            # for everything else (the lemma `step_load_value` needs the memory written as `Int.toBytes 8 v`)
            unit.update(rD=rD, rB=rB, disp=disp, form="v" if v[0] in ("RCV", "BF", "PTR", "IMM") else "b")
            st.r[rD] = v
            pend.append(unit)
        elif k == "st":
            rS, rB, disp = op[1], op[2], op[3]
            v = st.r[rS]
            unit.update(rS=rS, rB=rB, disp=disp)
            if rB == "rsp":
                if rS == "rsp":
                    raise StepStop(i, f"directive {i} `{d}` stores rsp", "new directive form")
                stack_store(disp, v, i, d)
                pend.append(unit)
            elif st.r[rB][0] == "RCV":
                off = st.r[rB][1] + disp
                if seg_open is not None:
                    fP = fields[seg_open][2]
                    if off == fP and v == ("PTR", seg_open):
                        seg_open = None
                        complete(unit)
                    else:
                        raise StepStop(i, f"directive {i} `{d}`: store of {_vstr(v)} at receiver offset {off} where the "
                                        f"pointer tail of {fields[cur][0]} (ptr at {fP}) was expected", "other")
                elif cls == "u64" and off == fld()[2]:
                    if v != ("MEM", fld()[1]):
                        why = (f"directive {i} `{d}`: stores {_vstr(v)} into {name} (Go offset {off}); expected the 8 "
                               f"buffer bytes at the IR SSZ offset {fld()[1]}")
                        raise StepStop(i, why, "register" if v[0] == "UNK" else "other")
                    complete(unit)
                else:
                    ir_event(off, f"directive {i} `{d}`", i)
                    raise StepStop(i, f"directive {i} `{d}`: store of {_vstr(v)} at receiver offset {off}, no event of "
                                    f"field {name} ({cls})", "other" if cls != "none" else "new field kind")
            else:
                raise StepStop(i, f"directive {i} `{d}`: store through {rB} = {_vstr(st.r[rB])} (unknown base)", "register")
        elif k == "call":
            fn = op[1]
            if fn not in CALLEES.values():
                why = (f"directive {i} `callq {fn}`: callee without a proved spec" if not fn.startswith("runtime.")
                       else f"directive {i} `callq {fn}` outside a byte segment")
                raise StepStop(i, why, "new field kind" if cls == "none" else "other")
            if cls != "call" or info != fn:
                raise StepStop(i, f"directive {i} `callq {fn}`: the next IR field is {name} ({cls}"
                                f"{', callee ' + info if cls == 'call' else ''})",
                             # "set-up order" only when a LATER IR field has this callee; a callee that is not the
                             # overlay type of any later field (ValidatorIndex field calling Epoch) is "other"
                             "set-up order" if cls == "call" and any(f[3] == "call" and f[4] == fn for f in fields[cur + 1:])
                             else "other")
            end, ms, idx = step_window(dirs, a, [re.escape(f"callq {fn}"), r"test %rax,%rax", r"je (\S+)"], i,
                                     f"call block at {i}")
            lok = ms[2].group(1)
            j2 = step_label_index(dirs, lok, i)
            if j2 < end:
                raise StepStop(i, f"call at {i}: continuation label {lok} at {j2} not after the je", "other")
            src, fo = fld()[1], fld()[2]
            need = dict(rax=("RCV", fo), rbx=("BF", src), rcx=("IMM", 8))
            for r, want in need.items():
                if st.r[r] != want:
                    elsewhere = [x for x in STEP_R64 if st.r[x] == want]
                    why = (f"call at {i} ({name}): {r} = {_vstr(st.r[r])}, the call block needs {r} = {_vstr(want)}"
                           + (f" (it is in {', '.join(elsewhere)})" if elsewhere else ""))
                    # miss class: the wanted value in another register -> register; the right base without its
                    # offset (a load after the add) -> set-up order; the right base, another offset -> other (offset
                    # against the IR); an unknown / other value (clobbered) -> register
                    same = st.r[r][0] == want[0]
                    # "set-up order" only when the wanted adjustment (`add $off,%r`) ran in this field's
                    # set-up and a later directive replaced it; the right base with another offset is "other"
                    added = any(u.get("kind") == "add" and u.get("rD") == r and len(want) > 1 and u.get("imm") == want[1]
                                for u in pend)
                    cls_ = ("register" if elsewhere else "set-up order" if same and added
                            else "other" if same else "register")
                    raise StepStop(i, why, cls_)
            unit.update(kind="callblk", fn=fn, lok=lok, jc=idx[0], j2=j2, e=j2 + 1, last=end - 1)
            st.clobber()
            st.r["rax"], st.r["rbx"] = ("IMM", 0), ("IMM", 0)
            # the call block writes only sp + 8 of the frame (the callee's spill of rbx; `CALL_DECODE_STATEMENT`)
            for x in list(st.slot):
                if x != 8 and abs(x - 8) < 8 or x < 0:
                    st.slot[x] = ("UNK",)
            st.slot[8] = ("BF", src)
            complete(unit)
            i, a = j2 + 1, j2 + 1
            continue
        elif k == "lea_new":
            step_nested(dirs, st, fld(), cls, info, F, i, a, op[1], unit)
            pend.append(unit)
            complete()
            i, a = unit["e"], unit["e"]
            continue
        elif k == "lea_mk":
            if cls != "bytes":
                raise StepStop(i, f"directive {i}: byte segment, the next IR field is {name} ({cls})",
                             "set-up order" if cls != "none" else "new field kind")
            n, N = info, f"{info:#x}"
            endA, mA, iA = step_window(dirs, a, [re.escape("lea type__+387072(%rip),%rax"), r"xor %ebx,%ebx",
                                               rf"mov \$({SHX}),%ecx", r"callq runtime\.makeslice",
                                               rf"mov ({SHX})\(%rsp\),%(\w+)", rf"movq \$0x0,({SHX})?\(%(\w+)\)",
                                               rf"movq \$({SHX}),({SHX})?\(%(\w+)\)",
                                               r"cmpl \$0x0,runtime\.writeBarrier\(%rip\)", r"je (\S+)"],
                                     i, f"byte segment head at {i}")
            sz, dR, rX = _hexs(mA[2].group(1)), _hexs(mA[4].group(1)), mA[4].group(2)
            fL, fC = _step_disp(mA[5].group(1)), _step_disp(mA[6].group(2))
            lff = mA[8].group(1)
            jl = step_label_index(dirs, lff, i)
            if jl < endA:
                raise StepStop(i, f"byte segment at {i}: label {lff} not after the head window", "other")
            if n == FIELD_INLINE_SIZE:
                step_inline(dirs, st, fld(), F, i, a, endA, mA, iA, jl, unit)
                pend.append(unit)
                complete()
                i, a = unit["e"], unit["e"]
                continue
            rest = [rf"mov %rax,({SHX})\(%rsp\)", rf"mov %rax,({SHX})?\(%(\w+)\)", rf"mov ({SHX})\(%rsp\),%rbx"]
            i3 = jl + 1
            # the form is chosen by the directive after the buffer reload: `add $X,%rbx` or not
            _, _, ib = step_window(dirs, i3, rest, jl, f"byte segment middle at {jl}")
            k4 = ib[-1] + 1
            while k4 < len(dirs) and dirs[k4] == "nop":
                k4 += 1
            zform = not (k4 < len(dirs) and re.fullmatch(rf"add \$({SHX}),%rbx", dirs[k4]))
            pat = ([re.escape(f"{lff}:")] + rest + ([] if zform else [rf"add \$({SHX}),%rbx"])
                   + [rf"mov \$({SHX}),%ecx", r"callq runtime\.memmove", rf"mov ({SHX})\(%rsp\),%(\w+)",
                      rf"movq \$({SHX}),({SHX})?\(%(\w+)\)", rf"movq \$({SHX}),({SHX})?\(%(\w+)\)",
                      r"cmpl \$0x0,runtime\.writeBarrier\(%rip\)", r"jne (\S+)"])
            endB, mB, iB = step_window(dirs, jl, pat, jl, f"byte segment middle at {jl}")
            o = 0 if zform else 1
            dS, fP, rX2, dB = _hexs(mB[1].group(1)), _step_disp(mB[2].group(1)), mB[2].group(2), _hexs(mB[3].group(1))
            src_ = 0 if zform else _hexs(mB[4].group(1))
            sz2, dR2, rY = _hexs(mB[4 + o].group(1)), _hexs(mB[6 + o].group(1)), mB[6 + o].group(2)
            l1, fL2, rY1 = _hexs(mB[7 + o].group(1)), _step_disp(mB[7 + o].group(2)), mB[7 + o].group(3)
            c1, fC2, rY2 = _hexs(mB[8 + o].group(1)), _step_disp(mB[8 + o].group(2)), mB[8 + o].group(3)
            lwb = mB[10 + o].group(1)
            src, fo = fld()[1], fld()[2]
            checks = [
                (sz == n and sz2 == n and _hexs(mA[6].group(1)) == n and l1 == n and c1 == n,
                 f"size immediates {sz:#x} / {sz2:#x} / {l1:#x} / {c1:#x}, IR size {N}", "other"),
                (n in FIELD_SEGMENT_SIZES, f"size {n} (lemma sizes 20, 32, 48, 96)", "new field kind"),
                (mA[5].group(2) == rX and mA[6].group(3) == rX and rX2 == rX,
                 f"receiver register after makeslice not the same in its three uses ({rX}, {mA[5].group(2)}, "
                 f"{mA[6].group(3)}, {rX2})", "register"),
                (rY1 == rY and rY2 == rY, f"receiver register after memmove not the same ({rY}, {rY1}, {rY2})", "register"),
                (rX in STEP_RX, f"receiver register {rX} after makeslice (lemma: {', '.join(STEP_RX)})", "register"),
                (rY in STEP_RY, f"receiver register {rY} after memmove (lemma: {', '.join(STEP_RY)})", "register"),
                (dR2 == dR, f"the two receiver reloads use different slots ({dR:#x}, {dR2:#x})", "other"),
                (fP == fo, f"pointer store at Go offset {fP}, IR Go offset {fo}", "other"),
                (fL == fP + 8 and fL2 == fL and fC == fP + 16 and fC2 == fC,
                 f"len / cap stores at {fL} / {fC} (and {fL2} / {fC2}), pointer at {fP}", "other"),
                (src_ == src, f"source offset {src_} ({'offset-0 form' if zform else 'add form'}), IR SSZ offset {src}",
                 "other"),
                (st.slot.get(dR) == ("RCV", 0), f"slot {dR:#x} (receiver reload) holds {_vstr(st.slot.get(dR, ('UNK',)))}, "
                 f"not the receiver", "register"),
                (st.slot.get(dB) == ("BF", 0), f"slot {dB:#x} (buffer reload) holds {_vstr(st.slot.get(dB, ('UNK',)))}, "
                 f"not the buffer", "register"),
                (dS not in (dR, dB), f"pointer slot {dS:#x} is a reload slot", "other"),
                (min(dR, dB, dS) >= 0x18,
                 f"a slot below rsp + 0x18 (the makeslice / memmove argument area): {dR:#x}, {dB:#x}, {dS:#x}", "other"),
                (step_slot_ok(dS, F), f"pointer slot {dS:#x} outside the stack-store rule (multiple of 8, in [0, {F:#x}) "
                 f"or [{F + 16:#x}, {F + 48:#x}))", "other"),
            ]
            for ok, why, c in checks:
                if not ok:
                    raise StepStop(i, f"byte segment at {i} ({name}): {why}", c)
            unit.update(kind="seg", n=n, rX=rX, rY=rY, zform=zform, j1=a, nA=endA - a, j2=jl, nB=endB - jl,
                        jm=iB[6 if not zform else 5], e=endB, lff=lff, lwb=lwb, dR=dR, dB=dB, dS=dS, fP=fP,
                        fL=fL, fC=fC, src=src_)
            pend.append(unit)
            st.clobber(keep=())
            st.r[rY] = ("RCV", 0)
            for x in list(st.slot):
                if x < 0x18:
                    st.slot[x] = ("UNK",)
            for x in list(st.slot):
                if x != dS and abs(x - dS) < 8:
                    st.slot[x] = ("UNK",)
            st.slot[dS] = ("PTR", cur)
            seg_open = cur
            i, a = endB, endB
            continue
        else:
            why = f"directive {i} `{d}`: no step lemma for this directive form"
            raise StepStop(i, why, "new field kind" if cls == "none" else "new directive form")
        i += 1
        a = i
    # the epilogue is not checked here; `decoder_step` checks it as its own phase from this index
    return i


# the only value of `step_epilogue` that counts as an examined plain return (checked with `is`)
STEP_EPILOGUE_OK = object()


def step_epilogue(dirs, i, F):
    """The directives after the last field event (from `i`, following forward `jmp`s and labels) must be the
    plain return: only `nop`, labels, `mov d(%rsp),%rax|%rbx`, `xor %eax,%eax`, `xor %ebx,%ebx`, then
    `add $F,%rsp; pop %rbp; retq` with the head's frame size F. Any other directive (a store, a call, a branch)
    could change a decoded field after its event: StepEpilogueMiss (class other). A `jmp` to a label that is
    not in the file is a StepEpilogueMiss too. Returns STEP_EPILOGUE_OK only after `add $F,%rsp; pop %rbp; retq`."""
    seen = set()
    while True:
        if i >= len(dirs) or i in seen:
            raise StepEpilogueMiss(i, "epilogue: end of file or a loop before `add $F,%rsp; pop %rbp; retq`", "other")
        seen.add(i)
        d = dirs[i]
        if d == "nop" or label_of(d) is not None or re.fullmatch(r"mov (0x[0-9a-f]+)?\(%rsp\),%(rax|rbx)", d) \
                or d in ("xor %eax,%eax", "xor %ebx,%ebx"):
            i += 1
            continue
        m = re.fullmatch(r"jmp (\S+)", d)
        if m:
            try:
                jl = label_index(dirs, m.group(1))
            except NoMatch:
                raise StepEpilogueMiss(i, f"epilogue: directive {i} `{d}` jumps to a label that is not in the file (code "
                                   f"after the last field event is unknown)", "other")
            if jl <= i:
                raise StepEpilogueMiss(i, f"epilogue: directive {i} `{d}` jumps backwards", "other")
            i = jl
            continue
        if d == f"add ${F:#x},%rsp":
            rest = [x for x in dirs[i + 1:i + 6] if x != "nop"][:2]
            if rest == ["pop %rbp", "retq"]:
                return STEP_EPILOGUE_OK
            raise StepEpilogueMiss(i, f"epilogue: `{d}` not followed by `pop %rbp; retq`", "other")
        raise StepEpilogueMiss(i, f"epilogue: directive {i} `{d}` after the last field event is not part of the plain "
                           f"return (`mov d(%rsp),%rax|%rbx`, `xor`, `add ${F:#x},%rsp; pop %rbp; retq`): it could change "
                           f"a decoded field", "other")


