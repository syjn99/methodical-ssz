def _encoder_fast_path(args, flags):
    fast_path_gen = fast_path_module()
    # phase 1: the walk (two passes; FastPathRefuse on anything outside the interface)
    g = fast_path_gen.FastPathGenerator(args.assembly, args.const, args.ir, args.type, args.prefix, args.hand_layout, args.hand_layout_src)
    if not (g.ended and len(g.bstate) == len(g.fields) + 1 and g.done == len(g.fields)):
        raise fast_path_gen.FastPathRefuse("walk did not reach the return after every field")
    flags["walked"] = True
    # phase 2: the theorems
    body, kinds = g.text()
    flags["rendered"] = True
    px, n = args.prefix, len(g.fields)
    KH, KF, KE, KP = g.kind_names()
    want = ([(f"{px}_head", KH)] + [(f"{px}_field_{i}", KF) for i in range(n)]
            + [(f"{px}_epilogue", KE), (f"{px}_fast", KP)])
    if kinds != want:
        raise fast_path_gen.FastPathRefuse(f"kind lines emitted {kinds}, required {want}")
    for name, kind in want:
        if body.count(f"\ntheorem {name}_kind : ∀ (h : Host), type_of% (@{name} h)\n    = @Codec.{kind} h ") != 1 \
                or body.count(f"\ntheorem {name} : ") != 1 or body.count(f"theorem {name} ") + body.count(f"theorem {name}_kind ") != 2:
            raise fast_path_gen.FastPathRefuse(f"theorem {name} or its `_kind` line is missing or repeated")
    flags["kinds_complete"] = True
    tie, tail = "", ""
    if args.same_as:
        via = f"{args.same_as_via} " if args.same_as_via else ""
        tie = (f"\nThe statement implies the hand statement `{args.same_as}` through `{args.same_as_via}`."
               if args.same_as_via else f"\nThe statement is the declared type of the committed hand theorem `{args.same_as}`.")
        tail = (f"/-- Statement check: the generated theorem proves the hand statement"
                f"{' (implication tie)' if via else ''}. -/\n"
                f"theorem {px}_fast_statement_tie : type_of% (@{args.same_as} ‹Host›) :=\n  {via}{px}_fast\n\n")
    if args.same_as and tail.count(f"\ntheorem {px}_fast_statement_tie : ") != 1:
        raise fast_path_gen.FastPathRefuse("statement tie `_fast_statement_tie` missing")
    flags["statement_check"] = True
    meta = dict(g.meta(), statement_check=(f"same {args.same_as}" + (f" via {args.same_as_via}" if args.same_as_via else "")
                                           if args.same_as else "kind instance only"),
                assembly=args.assembly, ir=args.ir, ir_type=args.type, kinds=[dict(theorem=a, kind=b) for a, b in want])
    fixed = fast_path_gen.FAST_PATH_IMPORTS + g.imports()
    imports = list(fixed) + [m for m in args.imports.split(",") if m and m not in fixed]
    opens = " ".join(["Machine", "Runtime", "Codec"] + [o for o in args.open.split(",") if o])
    head = ("".join(f"import {m}\n" for m in imports) + "\n"
            f"/-!\n# Fast path (`encoder --fast-path`): encoder fast path of `(*v1alpha1.{g.t}).MarshalSSZTo`\n\n"
            "Generated from the `.S` file and the IR: a symbolic dataflow walk of the fast path, one application of a\n"
            "step lemma per directive (windows with the nops erased), boundary states between the fields. Every theorem\n"
            f"has a `_kind` line (`{KH}`, `{KF}`, `{KE}`, `{KP}`).\n"
            f"**Fast path only**: `len(dst) + {g.size} ≤ cap(dst)` and every byte-vector field of its exact length. No\n"
            "`runtime.growslice` directive is stepped: each capacity test is decided from the premise. Not covered: the\n"
            f"growslice branches, the length rejects, the morestack path. Not a complete encoder result.{tie}\n"
            + (f"Each nested pointer is not nil, and each nested call uses the function specification of its callee\n"
               f"(`{g.callee['holds']}`). Not covered: the `newobject` branch of a nil pointer and the\n"
               "error wrap of a nested call.\n" if g.nested else "") +
            f"FAST-PATH-JSON: {json.dumps(meta)}\n-/\n\n"
            f"open {opens}\nvariable [Host]\n\nnamespace {GEN_NS}\n\n")
    text = head + body + "\n" + tail + f"end {GEN_NS}\n"
    for bad in ("sorry", "admit", "native_decide", "bv_decide", "axiom ", "maxHeartbeats 4000001"):
        if bad in text:
            raise fast_path_gen.FastPathRefuse(f"forbidden text {bad!r} in the output")
    if g.nested:
        want_opts = sum(o.count("set_option ") for o in [fast_path_gen.NESTED_THEOREM_OPTIONS[r] for r in ("head", "epilogue", "fast")]
                        + [fast_path_gen.NESTED_THEOREM_OPTIONS["nested" if f[1] == "n" else "field"] for f in g.fields])
        if text.count("set_option ") != want_opts:
            raise fast_path_gen.FastPathRefuse("options differ from NESTED_THEOREM_OPTIONS")
    elif text.count("set_option maxHeartbeats ") != n + 3 or text.count("set_option maxHeartbeats 4000000 in\n") != n + 3:
        raise fast_path_gen.FastPathRefuse("heartbeat options differ from the interface's (4000000, one per theorem)")
    flags["verified"] = True
    return text


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("mode", choices=["uint64", "decoder", "encoder"])
    ap.add_argument("--assembly", required=True)
    ap.add_argument("--const", required=True)
    ap.add_argument("--name", help="uint64: the name of the theorem")
    ap.add_argument("--same-as", help="encoder --fast-path: NAME must be an independently written hand statement (a theorem "
                    "written by hand, not generated); emits `P_fast_statement_tie : type_of% (@NAME ‹Host›)`. A generated NAME is no "
                    "statement check (kindcheck rejects it)")
    ap.add_argument("--ir")
    ap.add_argument("--type")
    ap.add_argument("--prefix")
    ap.add_argument("--imports", required=True, action="append", help="modules to import, comma separated; the option can repeat")
    ap.add_argument("--open", default="")
    ap.add_argument("--whole-accept", action="store_true",
                    help="decoder: whole-accept: the step chain (a dataflow walk over the accept path with kinded "
                         "per-instruction step theorems, nop windows, register-parametric byte segments and call blocks) "
                         "plus the whole accept theorem and the size-reject theorem with their kinds; refuses (exit 2, "
                         "nothing on stdout) unless every theorem is emitted")
    ap.add_argument("--summary", help="decoder --whole-accept, encoder --fast-path: write the report (JSON) here")
    ap.add_argument("--fast-path", action="store_true",
                    help="encoder: the encoder fast-path theorem with head / field / epilogue theorems and their "
                         "kinds; refuses (exit 2, nothing on stdout) unless every theorem is emitted")
    ap.add_argument("--hand-layout", help="encoder --fast-path: use this committed EncoderFrameLayout (its stack chunk order) instead of a generated layout")
    ap.add_argument("--hand-layout-src", help="encoder --fast-path: the Lean file that defines --hand-layout")
    ap.add_argument("--same-as-via", help="encoder --fast-path --same-as: the implication lemma (kind instance -> hand statement)")
    args = ap.parse_args()
    args.imports = ",".join(args.imports)
    global GEN_NS
    GEN_NS = gen_ns(args.assembly, args.type) if args.assembly else None
    if args.mode == "encoder" or args.fast_path or args.hand_layout or args.hand_layout_src or args.same_as_via:
        if not (args.mode == "encoder" and args.fast_path):
            ap.error("encoder needs --fast-path; --fast-path / --hand-layout / --same-as-via are encoder options")
        if args.whole_accept or args.name:
            ap.error("encoder --fast-path excludes --whole-accept / --name")
        if not (args.ir and args.type and args.prefix):
            ap.error("encoder --fast-path needs --ir, --type, --prefix")
        if bool(args.hand_layout) != bool(args.hand_layout_src):
            ap.error("--hand-layout and --hand-layout-src go together")
        if args.same_as_via and not args.same_as:
            ap.error("--same-as-via needs --same-as")
        args.fast_path_summary = dict(type=args.type, mode="fast-path", generated=False)
        try:
            out = encoder_fast_path(args)
        except NoMatch as e:
            print(f"generator encoder: no fast-path theorem: {e}", file=sys.stderr)
            if args.summary:
                pathlib.Path(args.summary).write_text(json.dumps(dict(args.fast_path_summary, exit=2), indent=1) + "\n")
            sys.exit(2)
        if args.summary:
            pathlib.Path(args.summary).write_text(json.dumps(dict(args.fast_path_summary, exit=0), indent=1) + "\n")
        sys.stdout.write(out)
        return
    if args.same_as:
        ap.error("--same-as is an encoder --fast-path option")
    if args.whole_accept:
        if args.mode != "decoder":
            ap.error("--whole-accept is a decoder option")
        if not (args.ir and args.type and args.prefix):
            ap.error("--whole-accept needs --ir, --type, --prefix")
        args.whole_accept_summary = dict(type=args.type, mode="whole-accept", accept_generated=False)
        args.summary_data = None
        try:
            out = decoder_whole_accept(args)
        except NoMatch as e:
            print(f"generator decoder: no accept theorem: {e}", file=sys.stderr)
            if args.summary:
                pathlib.Path(args.summary).write_text(json.dumps(dict(args.whole_accept_summary, exit=2), indent=1) + "\n")
            sys.exit(2)
        if args.summary:
            pathlib.Path(args.summary).write_text(json.dumps(dict(args.whole_accept_summary, exit=0), indent=1) + "\n")
        sys.stdout.write(out)
        return
    if args.mode == "decoder":
        ap.error("decoder needs --whole-accept")
    if args.summary:
        ap.error("--summary is an option of decoder --whole-accept and encoder --fast-path")
    try:
        out = uint64_decoder(args)
    except NoMatch as e:
        print(f"generator {args.mode}: no template match: {e}", file=sys.stderr)
        sys.exit(2)
    sys.stdout.write(out)


if __name__ == "__main__":
    main()
