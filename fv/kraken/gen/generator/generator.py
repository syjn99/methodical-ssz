def step_nested_text(C, prefix, fname, ssz, u):
    name = f"{prefix}_{fname}_nested"
    j1, j2, j3, nA, nB, jc = u["j1"], u["j2"], u["j3"], u["nA"], u["nB"], u["jc"]
    out = STEP_NESTED_OPTIONS + (f"/-- `{fname}` (nested Checkpoint, SSZ offset {ssz}, Go offset {u['fP']}): new object and callee "
                                  f"over the windows {j1}–{j1 + nA - 1} and {j2}–{j2 + nB - 1} (`callq` at {jc}), continuation "
                                  f"label at {j3}. -/\n")
    out += STEP_NESTED_STATEMENT.format(name=name, C=C, fn=u["fn"], dR=_i64(u["dR"]), dB=_i64(u["dB"]), dC=_i64(u["dC"]),
                                        fP=_i64(u["fP"]), src=_i64(u["src"]), j1=j1, jc=jc, j3=j3)
    lwb, lst, lok = lean_str(u["lwb"]), lean_str(u["lst"]), lean_str(u["lok"])
    out += f"  have hqA := Codec.window_infix_at hk {j1} {nA}\n"
    out += (f"  have heA : Codec.eraseNop (({C}.drop {j1}).take {nA}) = Codec.nestedCheckpointAllocate {lwb} {lst} "
            f"{_lit(u['dR'])} := by rfl\n")
    out += f"  have hqB := Codec.window_infix_at hk {j2} {nB}\n"
    out += (f"  have heB : Codec.eraseNop (({C}.drop {j2}).take {nB}) = Codec.nestedCheckpointCall {lst} {lean_str(u['fn'])} {lok} "
            f"{_lit(u['fP'])} {_lit(u['dB'])} {_lit(u['src'])} {_lit(u['dC'])} {_lit(u['rest'])} := by rfl\n")
    out += f"  have hjl : k + {j2} + Codec.nonNopIndex (({C}.drop {j2}).take {nB}) 0 = k + {j2} := by rfl\n"
    out += step_label_have("hls", j2, C)
    out += f"  have hjc : k + {j2} + Codec.nonNopIndex (({C}.drop {j2}).take {nB}) 7 = k + {jc} := by rfl\n"
    out += (f"  have hB := Codec.infix_sub (q := Codec.callDecodeContinuationLabel {lok}) {j3} hk\n"
            f"    (by simp only [{C}, Codec.callDecodeContinuationLabel, {SIMP_INFIX}])\n")
    out += step_label_have("hl", j3, C)
    out += (f"  with_reducible exact Codec.nested_checkpoint_decode_window _ _ _ _ _ _ _ _ _ _ _ _ (k + {j1}) (k + {j2}) "
            f"(k + {j3}) (k + {j2}) (k + {jc}) hqA heA hqB heB hjl hls hjc hB hl\n")
    kpar = (f"{C} {lean_str(u['fn'])} {j1} {jc} {j3} {_lit(u['dR'])} {_lit(u['fP'])} {_lit(u['dB'])} {_lit(u['src'])} "
            f"{_lit(u['dC'])}")
    out += kind_thm(name, f"Codec.nestedCheckpointDecodeKindWindow h {kpar}")
    return out + "\n", name


STEP_FLAGS = ("head_ok", "fields_complete", "epilogue_ok")


def step_fail_closed(args, why):
    """The step walk reports no field covered (NoMatch): every IR field `not covered`, class other."""
    summ, fields = args.summary_data, getattr(args, "step_fields", None) or []
    if summ is not None:
        summ["fail_closed"] = why
        summ["fields"] = [dict(field=fname, ssz_offset=src, go_offset=fo, status="not covered", reached=False,
                               reason=f"fail-closed: {why}", miss_class="other") for (fname, src, fo, cls, info) in fields]
    raise NoMatch(f"step: {why}; no field is reported covered")


def decoder_step(args):
    """The step front end of `decoder --whole-accept`: the dataflow walk; returns the step chain text or raises NoMatch
    (no field covered) / Partial (some fields covered).
    FAIL-CLOSED: the `else` branch below is the ONLY place that returns a text. It is reached only
    when `_decoder_step` completed normally AND set all three flags of STEP_FLAGS: `head_ok` (step_head returned),
    `fields_complete` (the walk returned without a stop, every IR field completed in IR order) and `epilogue_ok`
    (step_epilogue returned STEP_EPILOGUE_OK). NoMatch / Partial propagate; ANY other exception of any phase
    (also SystemExit, but not KeyboardInterrupt) becomes NoMatch with every field not covered."""
    flags = dict.fromkeys(STEP_FLAGS, False)
    try:
        text = _decoder_step(args, flags)
    except (NoMatch, Partial):
        raise
    except KeyboardInterrupt:
        raise
    except BaseException as e:
        step_fail_closed(args, f"internal error {type(e).__name__}: {e}")
    else:
        if all(flags[k] is True for k in STEP_FLAGS) and isinstance(text, str):
            assert all(flags[k] is True for k in STEP_FLAGS)
            return text
        step_fail_closed(args, f"success flags not all set ({', '.join(k for k in STEP_FLAGS if flags[k] is not True)})")
    raise AssertionError("unreachable: step_fail_closed raises")


def _decoder_step(args, flags):
    dirs, sha = read_S(args.assembly)
    fields, irsha = ir_fields(args.ir, args.type)
    summ = args.summary_data = dict(type=args.type, assembly=args.assembly, assembly_sha256=sha, ir_sha256=irsha, fields=[])
    args.step_fields = fields
    if not fields:
        raise NoMatch(f"{args.type}: no field")
    if len({f[0] for f in fields}) != len(fields):
        raise NoMatch(f"{args.type}: a field name repeats")
    ssz_size = ir_ssz_size(args.ir, args.type)  # an IR error (NoMatch) here has no field list
    # phase 1: head. ANY exception is a head miss (NoMatch); only a normal return sets head_ok
    try:
        head_end, slots, F = step_head(dirs, ssz_size)
    except Exception as e:
        hm = isinstance(e, StepHeadMiss)
        why, mcls = (e.why, e.cls) if hm else (f"step head: internal error {type(e).__name__}: {e}", "other")
        # a head miss is reported per field (class, `reached: false`) before the NoMatch
        summ["head"] = dict(status="not covered", reason=why, miss_class=mcls)
        for (fname, src, fo, cls, info) in fields:
            summ["fields"].append(dict(field=fname, ssz_offset=src, go_offset=fo, status="not covered", reached=False,
                                       reason=f"not reached: {why}", miss_class=mcls))
        raise NoMatch(why)
    flags["head_ok"] = True
    summ["head"] = dict(status="covered", end=head_end, frame=F)
    C, pre = args.const, args.prefix
    # phase 2: fields. Complete only when the walk returned without a stop and the field events are 0..n-1 in order
    done, stop, end = step_walk(dirs, fields, head_end, slots, F)
    if stop is None and end is not None and [y for (y, _) in done] == list(range(len(fields))):
        flags["fields_complete"] = True
        # phase 3: epilogue. ANY exception or any return value other than STEP_EPILOGUE_OK: no field is covered (NoMatch)
        try:
            r = step_epilogue(dirs, end, F)
        except Exception as e:
            r = e
        if r is STEP_EPILOGUE_OK:
            flags["epilogue_ok"] = True
            summ["epilogue"] = dict(status="covered")
        else:
            at = r.at if isinstance(r, StepStop) else end
            why = r.why if isinstance(r, StepStop) else f"epilogue: no explicit success ({type(r).__name__}: {r})"
            # a directive after the last field event could change any decoded field: no field is covered
            summ["epilogue"] = dict(status="not covered", at=at, reason=why)
            for (fname, src, fo, cls, info) in fields:
                summ["fields"].append(dict(field=fname, ssz_offset=src, go_offset=fo, status="not covered", reached=True,
                                           reason=f"{why} (directive {at})", miss_class="other"))
            raise NoMatch(f"step: {why} (directive {at}); no field is reported covered")
    else:
        summ["epilogue"] = dict(status="not examined")
    body, report, ncov, used = "", [], 0, set()
    for x, (fname, src, fo, cls, info) in enumerate(fields):
        rec = dict(field=fname, ssz_offset=src, go_offset=fo)
        units = [u for (y, us) in done if y == x for u in us]
        if any(y == x for (y, _) in done):
            names = []
            for u in units:
                if u["kind"] == "callblk":
                    t, nm = step_call_text(C, pre, fname, u)
                    used.add("call")
                elif u["kind"] == "seg":
                    t, nm = step_seg_text(C, pre, fname, src, u)
                    used.add("segz" if u["zform"] else "seg")
                elif u["kind"] == "inline":
                    t, nm = step_inline_text(C, pre, fname, src, u)
                    used.add("inline")
                elif u["kind"] == "nested":
                    t, nm = step_nested_text(C, pre, fname, src, u)
                    used.add("nested")
                else:
                    t, nm = step_step_text(C, pre, u)
                body += t
                names.append(nm)
            lo, hi = min(u["j"] for u in units), max(u["e"] for u in units) - 1
            if cls == "call":
                shape = f"call field ({info.split('.')[-2]}): {len(units) - 1} set-up steps + call block"
            elif cls == "bytes":
                shape = f"byte field ({info} bytes): {sum(u['kind'] not in ('seg', 'inline') for u in units)} steps + segment"
            elif cls == "nested":
                shape = f"nested field ({info.split('.')[-2]}): {len(units) - 1} set-up steps + nested block"
            else:
                shape = f"uint64 field: {len(units)} steps"
            rec.update(status="covered", reached=True, shape=shape, directives=[lo, hi], theorems=names)
            report.append(f"field {fname}: MATCH {shape}, directives {lo}–{hi}")
            ncov += 1
        else:
            if cls == "none":
                why, mc = info, "new field kind"
                if stop is not None and x == len(done):
                    why += f" (the walk stopped at directive {stop.at}: {stop.why})"
            elif stop is not None and x == len(done):
                why, mc = stop.why, stop.cls
            else:
                why, mc = (f"not reached: the walk stopped in field {fields[len(done)][0]} ({stop.why})", "other")
            # `reached` is false for every field after the one where the walk stopped (its class says nothing)
            rec.update(status="not covered", reached=x == len(done), reason=why, miss_class=mc)
            report.append(f"field {fname}: NOT COVERED [{mc}]: {why}")
        summ["fields"].append(rec)
    if not ncov:
        raise NoMatch("; ".join(report))
    kinds = (["Codec.Kind.WindowSteps", "Codec.Kind.FixedBytesDecodeWindow", "Codec.Kind.CalleeDecodeWindow"]
             + (["Codec.Kind.FixedBytesDecodeWindowOffsetZero"] if "segz" in used else [])
             + (["Codec.Kind.FixedBytesDecodeInline"] if "inline" in used else [])
             + (["Codec.Kind.NestedCheckpointDecode"] if "nested" in used else []))
    # the coverage header text is fixed: `kindcheck.py` rule 11 reads it
    extra = (f" and `{args.ir}` (sha256 `{irsha}`, type `{args.type}`); step coverage: "
             f"{ncov} of {len(fields)} fields; step chain from directive {head_end} (end of the head)")
    body += f"end {GEN_NS}\n"
    # the theorems of each covered field, machine-readable (`kindcheck.py` rule 10 counts the fields from it: a
    # uint64 field has only step theorems, so its field is not visible in the theorem names)
    fj = [dict(field=r["field"], theorems=r["theorems"]) for r in summ["fields"] if r["status"] == "covered"]
    fblock = (f"/-! Step chain fields (machine-readable, read by `kindcheck.py`):\nFIELDS-JSON: {json.dumps(fj)}\n-/\n\n")

    def gheader():
        h = header(sha, args.assembly, args, extra, kinds)
        assert h.count("\nopen Machine Runtime ") == 1
        return h.replace("\nopen Machine Runtime ", "\n" + fblock + "open Machine Runtime ")
    if ncov == len(fields):
        return gheader() + body
    raise Partial(report)


# ---------------------------------------------------------------- whole-accept: generated whole accept theorem

WHOLE_ACCEPT_FLAGS = ("step_ok", "derived", "rendered", "kinds_complete", "statement_check")


def decoder_whole_accept(args):
    """`decoder --whole-accept`: the step walk as front end, then the whole accept theorem (head, one theorem per field,
    epilogue, accept, size reject), every statement with its `_kind` line (the whole-accept lemmas).
    FAIL-CLOSED: the `else` branch below is the ONLY place that returns a text (exit 0). It is reached only when
    `_decoder_whole_accept` completed normally AND set every flag of WHOLE_ACCEPT_FLAGS. ANY exception of any phase (also a step
    `Partial`, a `WholeAcceptRefuse`, an unexpected error, SystemExit; not KeyboardInterrupt) is exit 2: nothing on stdout,
    no accept theorem."""
    flags = dict.fromkeys(WHOLE_ACCEPT_FLAGS, False)
    try:
        text = _decoder_whole_accept(args, flags)
    except KeyboardInterrupt:
        raise
    except BaseException as e:
        why = e.why if hasattr(e, "why") and isinstance(getattr(e, "why"), str) else str(e)
        if isinstance(e, Partial):
            why = "the step front end covers only some fields: " + "; ".join(e.report)
        args.whole_accept_summary.update(accept_generated=False, reason=f"{type(e).__name__}: {why}")
        raise NoMatch(f"whole-accept: no accept theorem ({type(e).__name__}: {why})")
    else:
        if all(flags[k] is True for k in WHOLE_ACCEPT_FLAGS) and isinstance(text, str):
            args.whole_accept_summary.update(accept_generated=True, reason="")
            return text
        missing = [k for k in WHOLE_ACCEPT_FLAGS if flags[k] is not True]
        args.whole_accept_summary.update(accept_generated=False, reason=f"success flags not set: {missing}")
        raise NoMatch(f"whole-accept: success flags not all set ({', '.join(missing)}); no accept theorem")
    raise AssertionError("unreachable")


