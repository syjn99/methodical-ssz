#!/usr/bin/env python3
"""Untrusted proof-text generator for the parameterized lemmas of `lean/Codec`.

Reads a committed normalized `.S` file (one directive per non-empty line) and, for containers, the IR
(`prysm/ir/ir-mainnet.json`: SSZ fixed sizes of the fields and the gc amd64 Go field offsets).
Emits Lean text that applies the parameterized lemmas of `lean/Codec` to the code constant of the function:

  uint64                    the accept path of a uint64 primitive `UnmarshalSSZ` (`Codec.uint64_decode_accept`).
  decoder --whole-accept    the step chain of the accept path (see the block comment before `STEP_R64`), then the
                            head, field, epilogue, accept and size-reject theorems (`whole_accept.py`).
  encoder --fast-path       the encoder fast-path theorem of a flat `MarshalSSZTo`, or of one with nested Checkpoint fields (`fast_path.py`).

Statement check: every emitted theorem `t` is followed by
`t_kind : ∀ (h : Host), type_of% (@t h) = <kind> h <parameters>` proved by `with_reducible rfl`. The kind
is hand text in `lean/Codec/Kind/*.lean`, proved from its lemma. `@t h` is the whole
declared type, binders before and after the colon. So the kernel checks the full emitted statement against
the kind; it does not need a hand theorem of the instance type. What it does not check: that the
parameters given to the kind are the right ones for the Go type. A wrong parameter gives a statement that
the code facts of the proof do not support, so the build fails; that is a property of the proof, not of
the `_kind` check. `kindcheck.py` checks by text that every `_kind` line names a kind of `lean/Codec/Kind/`.

Nothing here is trusted: the output is ordinary Lean, checked by the kernel. A wrong read of
the `.S` (wrong label, index, displacement) makes the code hypotheses of the lemma
unprovable and the generated file fails to build. The generator also checks every directive
of a template textually and stops (exit 2, message on stderr) when one does not match: a
compiler variation that the template does not cover is reported, not patched.

Python 3 standard library only. Usage:
  generator.py uint64 --assembly FILE --const LEAN_CONST --name THM --imports M1,M2 [--open NS]
  generator.py decoder --whole-accept --assembly FILE --const LEAN_CONST --ir IR.json --type PKGSUFFIX.TYPE --prefix NAME
                   --imports M1,M2 [--open NS] [--summary FILE.json]
  generator.py encoder --fast-path --assembly FILE --const LEAN_CONST --ir IR.json --type PKGSUFFIX.TYPE --prefix NAME
                   --imports M1,M2 [--open NS] [--hand-layout NAME --hand-layout-src FILE]
                   [--same-as HAND_THM [--same-as-via LEMMA]] [--summary FILE.json]
`--imports` can repeat. The output imports the modules of all its values, in order.
"""
import argparse, hashlib, json, pathlib, re, sys

HEX = r"0x[0-9a-f]+"


class NoMatch(Exception):
    pass


def read_S(path):
    raw = pathlib.Path(path).read_bytes()
    lines = [l.strip() for l in raw.decode("ascii").split("\n")]
    return [l for l in lines if l], hashlib.sha256(raw).hexdigest()


def label_of(d):
    return d[:-1] if d.endswith(":") else None


def expect(dirs, i, rx, what):
    if i >= len(dirs):
        raise NoMatch(f"directive {i}: end of file, expected {what}")
    m = re.fullmatch(rx, dirs[i])
    if not m:
        raise NoMatch(f"directive {i}: `{dirs[i]}` is not {what} (/{rx}/)")
    return m


def label_index(dirs, l):
    for i, d in enumerate(dirs):
        if label_of(d) == l:
            return i
    raise NoMatch(f"label {l} not found")


def lean_str(s):
    if '"' in s or "\\" in s:
        raise NoMatch(f"label with a quote or backslash: {s}")
    return f'"{s}"'


# The namespace of every output: Prysm.<Go type name>, from --type (`<package>.<Type>`), or for uint64 (no --type) from
# the name of the `.S` file (`<package>.<Type>.<Method>.S`). A `.S` file of another name (a test mutant) gives
# Prysm.Unknown; the generator checks the text in the same way.
GEN_NS = None


def gen_ns(s_path, type_name=None):
    if type_name:
        return "Prysm." + type_name.rsplit(".", 1)[-1]
    parts = pathlib.Path(s_path).name.split(".")
    return "Prysm." + (parts[-3] if len(parts) >= 4 else "Unknown")


def header(src_sha, src, args, extra="", kinds=()):
    mods = args.imports.split(",")
    # the statement kinds; `kinds` adds the kind and lemma modules of the step chain
    mods = mods + [m for m in ["Codec.Kind.FieldPatterns", *kinds] if m not in mods]
    imports = "\n".join(f"import {m}" for m in mods)
    return (f"{imports}\n\n/-! Generated by `gen/generator/generator.py {args.mode}` from `{src}`\n"
            f"(sha256 `{src_sha}`){extra}. Untrusted generator: this file is checked by Lean like any other.\n"
            f"Do not edit by hand. -/\n\n"
            f"open Machine Runtime {args.open}\nvariable [Host]\n\nopen Codec\nnamespace {GEN_NS}\n\n")


SIMP_INFIX = ("List.drop_succ_cons, List.drop_zero, List.length_cons, List.length_nil, List.take_succ_cons, "
              "List.take_zero")


def infix_have(name, tmpl_call, at, const):
    return (f"  have {name} := Codec.infix_sub (q := {tmpl_call}) {at} hk\n"
            f"    (by simp only [{const}, {tmpl_call.split()[0]}, {SIMP_INFIX}])\n")


def label_have(name, j, const):
    return (f"  have {name} := Machine.label_at' hk hf (j := {j})\n"
            f"    (by simp only [{const}, List.getElem?_cons_succ, List.getElem?_cons_zero]; rfl)\n"
            f"    (by simp only [{const}, List.take_succ_cons, List.take_zero, List.contains_cons, List.contains_nil]; decide)\n")


def kind_thm(name, kind):
    """The whole declared type of `name` (binders before the colon included) is the
    statement kind. Emitted directly after the theorem; `negative.py` keeps it in a mutant of `name`."""
    return (f"theorem {name}_kind : ∀ (h : Host), type_of% (@{name} h) = @{kind} := by\n"
            f"  intro h; with_reducible rfl\n")


# ---------------------------------------------------------------- uint64 decoder

UINT64_DECODER_STATEMENT = """theorem {name} (k : Nat) (hk : {const}.IsInfixAt Host.prog k)
    (hf : LabelsFresh {const} k)
    (e8 : List UInt8) (he8 : e8.length = 8)
    (s : MachineData) (ra guard : UInt64) (fp s2 c0 : List UInt8)
    (hfp : fp.length = 8) (h2 : s2.length = 8) (hc0 : c0.length = 8) (R : DataMem → Prop)
    (h_mem : s.dmem =⋆ Eq ((Int.toBytes 8 ra.toBitVec.toInt).At s.regs.rsp.toBitVec)
      ⋆ Eq (fp.At (s.regs.rsp.toBitVec - 8)) ⋆ Eq (s2.At (s.regs.rsp.toBitVec + 16))
      ⋆ Eq ((Int.toBytes 8 guard.toBitVec.toInt).At (s.regs.r14.toBitVec + 16))
      ⋆ Eq (e8.At s.regs.rbx.toBitVec) ⋆ Eq (c0.At s.regs.rax.toBitVec) ⋆ R)
    (hguard : guard.toNat < s.regs.rsp.toNat) (hlen : s.regs.rcx = 8) :
    Eventually (step1 Host.exe)
      (fun st => st.pc = Int64.ofBitVec ra.toBitVec ∧ st.data.regs.rax = 0 ∧ st.data.regs.rbx = 0
        ∧ st.data.regs.rsp = s.regs.rsp + 8 ∧ st.data.regs.rbp = s.regs.rbp ∧ st.data.regs.r14 = s.regs.r14
        ∧ (Eq ((Int.toBytes 8 ra.toBitVec.toInt).At s.regs.rsp.toBitVec)
          ⋆ Eq ((Int.toBytes 8 s.regs.rbp.toBitVec.toInt).At (s.regs.rsp.toBitVec - 8))
          ⋆ Eq ((Int.toBytes 8 s.regs.rbx.toBitVec.toInt).At (s.regs.rsp.toBitVec + 16))
          ⋆ Eq ((Int.toBytes 8 guard.toBitVec.toInt).At (s.regs.r14.toBitVec + 16))
          ⋆ Eq (e8.At s.regs.rbx.toBitVec) ⋆ Eq (e8.At s.regs.rax.toBitVec) ⋆ R) st.data.dmem)
      ⟨s, Host.addrOf k⟩ := by
"""


def uint64_decoder_read(dirs):
    fn = label_of(dirs[0]) or (_ for _ in ()).throw(NoMatch("directive 0 is not a label"))
    l0 = label_of(dirs[1]) or (_ for _ in ()).throw(NoMatch("directive 1 is not a label"))
    expect(dirs, 2, r"cmp 0x10\(%r14\),%rsp", "the stack guard compare")
    lcc = expect(dirs, 3, r"jbe (\S+)", "jbe <morestack label>").group(1)
    expect(dirs, 4, r"push %rbp", "push %rbp")
    expect(dirs, 5, r"mov %rsp,%rbp", "mov %rsp,%rbp")
    fs = int(expect(dirs, 6, rf"sub \$({HEX}),%rsp", "sub $fs,%rsp").group(1), 16)
    dsp = int(expect(dirs, 7, rf"mov %rbx,({HEX})\(%rsp\)", "the rbx spill").group(1), 16)
    if dsp != fs + 24:
        raise NoMatch(f"rbx spill at {dsp:#x}(%rsp) is not fs + 24 = {fs + 24:#x} (caller slot rsp + 16)")
    expect(dirs, 8, r"nop", "nop")
    expect(dirs, 9, r"cmp \$0x8,%rcx", "cmp $0x8,%rcx")
    lbb = expect(dirs, 10, r"je (\S+)", "je <accept label>").group(1)
    jb = label_index(dirs, lbb)
    tail = [r"mov \(%rbx\),%rcx", r"nop", r"mov %rcx,\(%rax\)", r"xor %eax,%eax", r"xor %ebx,%ebx",
            rf"add \${fs:#x},%rsp", r"pop %rbp", r"retq"]
    for n, rx in enumerate(tail):
        expect(dirs, jb + 1 + n, rx, f"uint64 decoder tail directive {n + 1}")
    return dict(fn=fn, l0=l0, lcc=lcc, lbb=lbb, fs=fs, dsp=dsp, jb=jb)


def uint64_decoder(args):
    dirs, sha = read_S(args.assembly)
    p = uint64_decoder_read(dirs)
    c = args.const
    out = header(sha, args.assembly, args, f"; uint64 decoder parameters: frame {p['fs']:#x}, spill {p['dsp']:#x}, "
                 f"accept label at directive {p['jb']}")
    out += "set_option maxRecDepth 100000 in\n"
    out += UINT64_DECODER_STATEMENT.format(name=args.name, const=c)
    head = (f"Codec.uint64DecodeHead {lean_str(p['fn'])} {lean_str(p['l0'])} {lean_str(p['lcc'])} "
            f"{lean_str(p['lbb'])} {p['fs']} {p['dsp']}")
    out += infix_have("hA", head, 0, c)
    out += infix_have("hB", f"Codec.uint64DecodeTail {lean_str(p['lbb'])} {p['fs']}", p["jb"], c)
    out += label_have("hl", p["jb"], c)
    out += (f"  with_reducible exact (Codec.uint64_decode_accept _ _ _ _ {p['fs']} {p['dsp']} (by decide) k (k + {p['jb']})\n"
            f"    hA hB hl e8 he8 s ra guard fp s2 c0 hfp h2 hc0 R h_mem hguard hlen)\n")
    out += kind_thm(args.name, f"Codec.uint64DecodeAcceptKind h {c}")
    out += f"\nend {GEN_NS}\n"
    return out


# ---------------------------------------------------------------- step chain: IR fields

class Partial(Exception):
    """The step walk covers some fields and not others. Carries the per-field report."""

    def __init__(self, report):
        super().__init__("partial")
        self.report = report


FIELD_SEGMENT_SIZES = (32, 48, 96, 20)
SIZE_CASE_PROOF = {32: "Or.inl rfl", 48: "Or.inr (Or.inl rfl)", 96: "Or.inr (Or.inr (Or.inl rfl))", 20: "Or.inr (Or.inr (Or.inr rfl))"}
# the byte vector size of the inline-copy segment (`bytes_decode_inline_segment_window`: no memmove, a 32-bit copy)
FIELD_INLINE_SIZE = 4


def ir_fields(ir_path, tname):
    """Every own field of the container, in IR order: (name, SSZ offset, Go offset, class, size, callee label or reason).
    class: "bytes" (fixed `[]byte` vector, size 4 / 20 / 32 / 48 / 96), "u64" (`uint64`), "call" (a uint64 overlay that a callee
    with a proved spec decodes), "none" (not covered)."""
    raw = pathlib.Path(ir_path).read_bytes()
    pkg, name = tname.rsplit(".", 1)
    ts = [t for c in json.loads(raw)["configs"] for t in c.get("types", [])
          if t.get("name") == name and t.get("package", "").endswith("/" + pkg)]
    if not ts:
        raise NoMatch(f"type {tname} not in the IR")
    t = ts[0]
    goff = {f["name"]: f["offset_gc_amd64"] for f in t["go_fields"]}
    out, off = [], 0
    for f in t["ir"]["fields"]:
        v = f["v"]
        if v.get("variable"):
            raise NoMatch(f"field {f['key']} is variable-size (not a flat container)")
        k, fo = v.get("k"), goff.get(f["key"])
        if fo is None:
            cls, info = "none", "no Go field offset in the IR"
        elif k == "vector" and v.get("elem", {}).get("k") == "byte" and v.get("go_type") == "[]byte":
            if v.get("size") in FIELD_SEGMENT_SIZES + (FIELD_INLINE_SIZE,) and v.get("fixed_size") == v.get("size"):
                cls, info = "bytes", v["size"]
            else:
                cls, info = "none", f"byte vector of size {v.get('size')} (lemma sizes 4, 20, 32, 48, 96 only)"
        elif k == "uint" and v.get("bits") == 64 and v.get("go_type") == "uint64" and v.get("fixed_size") == 8:
            cls, info = "u64", 8
        elif k == "pointer" and v.get("deleg"):
            cls, info = ir_nested_class(v)
        elif k == "overlay" or v.get("deleg"):
            cls, info = ir_callee_class(v)
        else:
            cls, info = "none", f"field kind {k} ({v.get('go_type')}): no step form (nested containers, lists, bitfields, bool, other uints)"
        out.append((f["key"], off, fo, cls, info))
        off += v["fixed_size"]
    return out, hashlib.sha256(raw).hexdigest()


def ir_ssz_size(ir_path, tname):
    """The SSZ fixed size of a fixed-size container: the sum of the field sizes in the IR; it must
    equal the container's own `fixed_size` in the IR, else NoMatch."""
    pkg, name = tname.rsplit(".", 1)
    ts = [t for c in json.loads(pathlib.Path(ir_path).read_bytes())["configs"] for t in c.get("types", [])
          if t.get("name") == name and t.get("package", "").endswith("/" + pkg)]
    if not ts:
        raise NoMatch(f"type {tname} not in the IR")
    ir = ts[0]["ir"]
    total = sum(f["v"]["fixed_size"] for f in ir["fields"])
    if ir.get("variable") or ir.get("fixed_size") != total:
        raise NoMatch(f"type {tname}: IR fixed size {ir.get('fixed_size')} is not the sum of the field sizes {total}")
    return total


# callee decoders with a proved accept spec (`Codec.Uint64CalleeAccept` of `lean/Codec/CalleeDecode.lean`, proved by
# `Prysm.<Type>.Decode.accept_function_spec_holds`)
PRIM_PKG = "github.com/OffchainLabs/prysm/v7/consensus-types/primitives"
CALLEES = {n: f"github.com_OffchainLabs_prysm_v7_consensus_types_primitives.{n}.UnmarshalSSZ"
           for n in ("Slot", "CommitteeIndex", "ValidatorIndex", "Epoch")}


# nested container callees with a proved function specification (`Codec.NestedCheckpointCalleeAccept` of
# `lean/Codec/NestedCheckpointDecode.lean`, proved by `Prysm.Checkpoint.Decode.accept_function_spec_holds`): the Go
# type name -> the callee label. The SSZ size of the nested container is the `mov $0x28,%ecx` of the block.
V1ALPHA1_PKG = "github.com/OffchainLabs/prysm/v7/proto/prysm/v1alpha1"
NESTED_CALLEES = {"Checkpoint": "github.com_OffchainLabs_prysm_v7_proto_prysm_v1alpha1.Checkpoint.UnmarshalSSZ"}
NESTED_SIZE = {"Checkpoint": 40}
# the `lea` of the `abi.Type` word that the block passes to `runtime.newobject` (the type `typeCheckpoint` of the contract)
NESTED_TYPE_LEA = {"Checkpoint": "lea type__+1289312(%rip),%rax"}


def ir_nested_class(v):
    """IR class of a pointer field: ("nested", callee label) or ("none", reason)."""
    dt = v.get("delegated_to") or {}
    if not (v.get("deleg") or {}).get("unmarshaler") or dt.get("k") != "container" or v.get("variable") \
            or dt.get("variable") or v.get("go_type") != f"*{dt.get('name')}":
        return "none", (f"field kind {v.get('k')} ({v.get('go_type')}, delegated to {dt.get('k')} {dt.get('name')}): "
                        f"pointer field that is not a fixed-size nested container with an unmarshaler")
    if dt.get("pkg") != V1ALPHA1_PKG or dt.get("name") not in NESTED_CALLEES \
            or v.get("fixed_size") != NESTED_SIZE[dt["name"]] or dt.get("fixed_size") != NESTED_SIZE[dt["name"]]:
        return "none", (f"field kind {v.get('k')} ({v.get('go_type')}, delegated to {dt.get('k')} {dt.get('name')}): "
                        f"nested container without a proved function specification (only {', '.join(NESTED_CALLEES)})")
    return "nested", NESTED_CALLEES[dt["name"]]


def ir_callee_class(v):
    """IR class of a delegated field: ("call", callee label) or ("none", reason)."""
    dt, u = v.get("delegated_to") or {}, v.get("underlying") or {}
    if v.get("k") != "overlay":
        return "none", (f"field kind {v.get('k')} ({v.get('go_type')}, delegated to {dt.get('k')} {dt.get('name')}): "
                        f"nested container / pointer callee, no call step")
    if not (v.get("deleg") or {}).get("unmarshaler") or dt.get("k") != "overlay" or v.get("fixed_size") != 8 \
            or u.get("k") != "uint" or u.get("bits") != 64:
        return "none", f"overlay field ({v.get('go_type')}) that is not a delegated uint64 overlay"
    if v.get("pkg") != PRIM_PKG or v.get("name") not in CALLEES or dt.get("name") != v.get("name") \
            or dt.get("pkg") != PRIM_PKG:
        return "none", (f"overlay callee {v.get('pkg')}.{v.get('name')}: no proved callee accept spec "
                        f"(only {', '.join(CALLEES)} of consensus-types/primitives)")
    return "call", CALLEES[v["name"]]


def _hexs(s):
    """`0x10` / `-0x10` -> int."""
    return -int(s[1:], 16) if s.startswith("-") else int(s, 16)


def _lit(x):
    """Lean literal of an Int64 parameter (negative in parentheses)."""
    return f"({x})" if x < 0 else f"{x}"


