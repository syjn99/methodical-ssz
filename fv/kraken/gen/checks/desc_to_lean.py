#!/usr/bin/env python3
"""Render the `ssz` term of a Desc-checker input file (schema fvphase1c.desc/1) as Lean.

Usage: desc_to_lean.py <desc.json> <lean-name> > lean/Prysm/Checkpoint/SpecChecker.lean (lean-name: checkerDesc)
The namespace of the output is Prysm.<GoTypeName> (the `type` of the file).
The file is the producer's Desc for (v1alpha1, Checkpoint) that the Desc checker accepted
(gen/desc/results/main.result.json, record orig/prysm_v1alpha1.Checkpoint.desc.json, same sha256).
Only the kinds of that term are rendered (container, uint, byteVector); any other kind is an error.
Python 3 standard library only.
"""
import hashlib
import json
import sys

path, name = sys.argv[1:3]
raw = open(path, "rb").read()
d = json.loads(raw)
assert d["schema"] == "fvphase1c.desc/1"


def term(t):
    k = t["k"]
    if k == "uint":
        return f".uint {int(t['w'])}"
    if k == "byteVector":
        return f".byteVector {int(t['n'])}"
    if k == "container":
        names = ", ".join(json.dumps(n) for n in t["names"])
        fields = ", ".join(term(f) for f in t["fields"])
        return f".container [{names}] [{fields}]"
    raise SystemExit(f"kind {k} not rendered")


print(f"""import EthLib.Serialization.Ssz

/-! Generated by `gen/checks/desc_to_lean.py` from `prysm/go1.26.10/evidence/{path.rsplit('/', 1)[-1]}`
(sha256 `{hashlib.sha256(raw).hexdigest()}`): the producer's Desc of
`({d['package']}, {d['type']})` that the Desc checker accepted
(`gen/desc/results/main.result.json`, same sha256). Do not edit. -/

namespace Prysm.{d['type']}
open EthLib.Serialization.Ssz

def {name} : Desc := {term(d['ssz'])}

end Prysm.{d['type']}""")
