#!/usr/bin/env python3
"""Render the `ssz` term of a Desc-checker input file (schema fv.kraken.desc/1) as Lean.

It uses the method of `desc_to_lean.py`; it also renders `bitVector`, `vector` and `list`.
Usage: list_desc_to_lean.py <desc.json> <lean-name> > lean/Prysm/<GoTypeName>/SpecChecker.lean
The namespace of the output is Prysm.<GoTypeName> (the `type` of the file).
The file is the producer's Desc that the Desc checker accepted (gen/desc/results/main.result.json, same sha256).
The tracked copies are in prysm/go1.26.10/evidence/.
The directory in the header text is fixed: the tracked SpecChecker.lean files hold this text, and a change would change them.
Python 3 standard library only.
"""
import hashlib
import json
import sys

path, name = sys.argv[1:3]
raw = open(path, "rb").read()
d = json.loads(raw)
assert d["schema"] == "fv.kraken.desc/1"


def term(t):
    k = t["k"]
    if k == "uint":
        return f".uint {int(t['w'])}"
    if k == "byteVector":
        return f".byteVector {int(t['n'])}"
    if k == "bitVector":
        return f".bitVector {int(t['n'])}"
    if k == "vector":
        return f".vector ({term(t['elem'])}) {int(t['n'])}"
    if k == "list":
        return f".list ({term(t['elem'])}) {int(t['limit'])}"
    if k == "container":
        names = ", ".join(json.dumps(n) for n in t["names"])
        fields = ", ".join(term(f) for f in t["fields"])
        return f".container [{names}] [{fields}]"
    raise SystemExit(f"kind {k} not rendered")


print(f"""import EthLib.Serialization.Ssz

/-! Generated by `gen/checks/list_desc_to_lean.py` from `prysm/go1.26.10/evidence/lists-and-vectors/desc/{path.rsplit('/', 1)[-1]}`
(sha256 `{hashlib.sha256(raw).hexdigest()}`): the producer's Desc of
`({d['package']}, {d['type']})` that the Desc checker accepted
(`gen/desc/results/main.result.json`, same sha256). Do not edit. -/

namespace Prysm.{d['type']}
open EthLib.Serialization.Ssz

def {name} : Desc := {term(d['ssz'])}

end Prysm.{d['type']}""")
