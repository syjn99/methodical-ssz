#!/usr/bin/env python3
"""Go value checks of the witness states as Lean predicates (X3).

Usage: goval_lean.py <wit-dir> <out-dir>
  reads <wit-dir>/Wit*.lean (generated by gen/wit/run.py), writes
  <out-dir>/GoValCheck.lean    every fact bound to the Lean witness and every predicate, by rfl
  <out-dir>/GoValControl.lean  four false facts (each must fail to elaborate)
  <out-dir>/goval-facts.json   the facts, the Python verdict per witness, what is not bound

The facts are the ones of src/goval.py (slice headers, objects, bool bytes, the type word of the
errorString itab, initialized error globals, pairwise disjoint Go objects, s_mem chunks inside one
object or outside all), extracted from the generated text. The Lean file then
- binds each number to the Lean definitions of the witness module `Fk.<Wit>`: register values of
  `s0` and words/bytes of `block` (rfl; only for witnesses whose `block` has no parameters and only
  when the generated file is byte-identical to lean/Fk/<Wit>.lean, which regen.json shows);
- checks the predicates (`Gen1c.GoVal.*`, Bool functions) by rfl;
- takes the element size of []uint64 and the type descriptor of *errors.errorString from the
  included abi.Type bytes (`Fk.Data.uint64Type_size_kind`, `Fk.Data.errorStringPtrType_shape`, and
  the descriptor bytes in the block = `Fk.Data.errorStringPtrType`). Struct sizes and alignments
  (Scalars, ListU64, ...) come from src/layout.json (unsafe.Sizeof/Alignof of the Go 1.26.3 gc
  amd64 compiler, written by src/layout.go); no abi.Type of those structs is included.
Symbolic lengths are refused: a witness whose block has a piece of unknown length is an error
(exit 2), not a partial check.
Python 3 standard library only. Run with python3 -I -B.
"""
import json
import os
import re
import sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "src"))
import goval as G  # noqa: E402

BASE = G.BASE
PRELUDE = """import Fk

/-! Generated by fv/kraken/gen/wit/goval_lean.py. Go value predicates of the witness states. -/

namespace Gen1c.GoVal
open Fk

def le64 (bs : List UInt8) : Nat := bs.foldr (fun b acc => b.toNat + 256 * acc) 0
/-- The 8-byte little-endian word of a block at index `i` (address `0x10000 + i`). -/
def wordAt (b : List UInt8) (i : Nat) : Nat := le64 ((b.drop i).take 8)
def byteAt (b : List UInt8) (i : Nat) : Nat := (b.getD i 0).toNat
def regsN (s : MachineData) : List Nat :=
  [s.regs.rax, s.regs.rbx, s.regs.rcx, s.regs.rdx, s.regs.rsi, s.regs.rdi, s.regs.rsp, s.regs.rbp,
   s.regs.r8, s.regs.r9, s.regs.r10, s.regs.r11, s.regs.r12, s.regs.r13, s.regs.r14, s.regs.r15].map UInt64.toNat

/-- Go slice header (p, len, cap) of elements of `esz` bytes in the block [lo, hi). -/
def sliceOk (lo hi p l c esz : Nat) : Bool :=
  l ≤ c && c < 2 ^ 63 && (c == 0 || (lo ≤ p && p + c * esz ≤ hi && p % (min esz 8) == 0))
/-- Go object of `size` bytes at `a`, aligned to `align`, inside [lo, hi). -/
def objOk (lo hi a size align : Nat) : Bool := lo ≤ a && a + size ≤ hi && a % align == 0
def boolOk (v : Nat) : Bool := v ≤ 1
def pairwiseDisjoint : List (Nat × Nat) → Bool
  | [] => true
  | (a, b) :: t => t.all (fun (c, d) => b ≤ c || d ≤ a) && pairwiseDisjoint t
/-- every chunk lies inside one object or outside all objects -/
def chunksOk (objs chunks : List (Nat × Nat)) : Bool :=
  chunks.all fun (lo, hi) => objs.all fun (a, b) => (hi ≤ a || b ≤ lo) || (a ≤ lo && hi ≤ b)

/-- Element size of []uint64 = `Size_` of the included `abi.Type` of uint64. -/
def eszU64 : Nat := 8
theorem eszU64_abi [Host] : le64 (Fk.Data.typeSize Fk.Data.uint64Type) = eszU64 := by
  rw [Fk.Data.uint64Type_size_kind.1]; rfl
/-- Size_ and Kind_ of the included `abi.PtrType` of *errors.errorString. -/
theorem errorStringPtrType_abi [Host] :
    le64 (Fk.Data.typeSize Fk.Data.errorStringPtrType) = 8 ∧ Fk.Data.typeKind Fk.Data.errorStringPtrType = 22 := by
  rw [Fk.Data.errorStringPtrType_shape.1, Fk.Data.errorStringPtrType_shape.2.1]; exact ⟨rfl, rfl⟩

end Gen1c.GoVal

open Gen1c.GoVal Fk

set_option maxRecDepth 100000
"""


def has_params(txt):
    m = re.search(r"^def block (.*?):", txt, re.M)
    return bool(m and m[1].strip())


class Facts:
    def __init__(self):
        self.reg, self.word, self.byte, self.pred, self.objs, self.notes = {}, {}, {}, [], [], []
        self.ok = True

    def w(self, mem, a):
        v = mem.word(a)
        if v is not None:
            self.word[a] = v
        return v


def slice_fact(F, mem, name, p, l, c, esz, esz_src, esz_lean=None):
    if None in (p, l, c):
        F.notes.append(f"{name}: symbolic slice header")
        return
    ok = l <= c < 2 ** 63 and (c == 0 or (mem.inblock(p, c * esz) and p % min(esz, 8) == 0))
    F.ok &= ok
    F.pred.append((f"sliceOk {BASE} {mem.end} {p} {l} {c} {esz_lean or esz}", f"slice {name} esz from {esz_src}", ok))
    if c:
        F.objs.append((p, p + c * esz, name + ".data"))


def obj_fact(F, mem, ty, a, name, depth=0):
    t = G.TY[ty]
    ok = mem.inblock(a, t["size"]) and a % t["align"] == 0
    F.ok &= ok
    F.pred.append((f"objOk {BASE} {mem.end} {a} {t['size']} {t['align']}", f"object {name}: {ty} (layout.json)", ok))
    F.objs.append((a, a + t["size"], name))
    for f in t["fields"]:
        off, fn = f["offset"], f"{name}.{f['name']}"
        if f["kind"] == "slice":
            p, l, c = F.w(mem, a + off), F.w(mem, a + off + 8), F.w(mem, a + off + 16)
            esz = f["esz"]
            if esz == 8 and not f.get("elem"):    # []uint64: Size_ of the included abi.Type of uint64
                slice_fact(F, mem, fn, p, l, c, esz, "abi.Type uint64", "eszU64")
            else:                                  # []byte (1) or []*T (pointer word, layout.json)
                slice_fact(F, mem, fn, p, l, c, esz, "byte" if esz == 1 else "pointer (layout.json)")
            if f.get("elem") and None not in (p, l) and depth < 2:
                for i in range(l):
                    q = F.w(mem, p + 8 * i)
                    if q:
                        obj_fact(F, mem, f["elem"], q, f"{name}[{i}]", depth + 1)
        elif f["kind"] == "ptr":
            q = F.w(mem, a + off)
            if q:
                obj_fact(F, mem, f["elem"], q, fn, depth + 1)
            elif q is None:
                F.notes.append(f"{fn}: symbolic pointer")
        elif f["kind"] == "bool":
            v = mem.bytes.get(a + off)
            if v is None:
                F.notes.append(f"{fn}: symbolic bool")
            else:
                F.byte[a + off] = v
                F.ok &= v <= 1
                F.pred.append((f"boolOk {v}", f"bool {fn}", v <= 1))


def facts(path):
    txt = open(path).read()
    F = Facts()
    m = re.search(r"def P : Program := dataLabels \+\+ (\w+)", txt)
    regs = G.regs_of(txt)
    mem = G.Mem(txt)
    if mem.partial:
        raise SystemExit(f"{path}: symbolic length refused ({mem.partial})")
    if not m or regs is None or mem.note:
        F.notes.append(f"not a generated witness layout ({mem.note or 'no target or registers'})")
        return F, txt
    for i in (0, 1, 2, 5, 6):
        if regs[i] is not None:
            F.reg[i] = regs[i]
    rsp = regs[6]
    F.pred.append((f"({rsp} % 8 == 0 : Bool)", "rsp 8-aligned", rsp % 8 == 0))
    F.ok &= rsp % 8 == 0
    tgt = m[1]
    if tgt == "ValidateBitvector":
        slice_fact(F, mem, "buf", regs[0], regs[1], regs[2], 1, "byte")
    else:
        mm = re.fullmatch(r"(\w+?)(UnmarshalSSZ|MarshalSSZTo|SizeSSZ)", tgt)
        ty, meth = mm[1], mm[2]
        if meth != "SizeSSZ":
            slice_fact(F, mem, "buf" if meth == "UnmarshalSSZ" else "dst", regs[1], regs[2], regs[5], 1, "byte")
        if regs[0]:
            obj_fact(F, mem, ty, regs[0], "recv")
    labs = G.labels_of(txt)
    it = labs.get("go_itab._errors.errorString_error")
    F.typedesc = None
    if it is not None and ('go_itab._errors.errorString_error").toBitVec + 8)' in txt or f"(({it} : UInt64).toBitVec + 8))" in txt):
        w = F.w(mem, it + 8)
        good = w is not None and w != 0 and w % 8 == 0 and mem.inblock(w, G.TYPEDESC)
        F.ok &= good
        F.pred.append((f"objOk {BASE} {mem.end} {w} 56 8", "itab+8 points to a 56-byte descriptor in the block", good))
        if good:
            F.objs.append((w, w + G.TYPEDESC, "typedesc"))
            F.typedesc = w
    for g in sorted(set(re.findall(r'\.At \(label "(ssz\.Err\w+)"\)\.toBitVec\)', txt))):
        ga = labs.get(g)
        e0, e1 = F.w(mem, ga), F.w(mem, ga + 8)
        sp, ln = (F.w(mem, e1), F.w(mem, e1 + 8)) if e1 else (None, None)
        good = (it is not None and e0 == it and e1 not in (None, 0) and e1 % 8 == 0 and mem.inblock(e1, 16)
                and sp is not None and ln is not None and mem.inblock(sp, ln))
        F.ok &= good
        F.pred.append((f"({e0} == {it} : Bool) && objOk {BASE} {mem.end} {e1} 16 8 && objOk {BASE} {mem.end} {sp} {ln} 1",
                       f"{g} initialized (itab, errorString)", good))
        if good:
            F.objs.append((e1, e1 + 16, f"{g}.obj"))
    L = sorted((a, b) for a, b, _ in F.objs)
    disj = all(b <= c or d <= a for i, (a, b) in enumerate(L) for (c, d) in L[i + 1:])
    F.ok &= disj
    F.pred.append((f"pairwiseDisjoint {lean_pairs(L)}", "Go objects pairwise disjoint", disj))
    lens = {k: int(v) for k, v in re.findall(r"\(\w+ : (\w+)\.length = (\d+)\)", txt)}
    lens.update({k: int(v) for k, v in re.findall(r"theorem \w+ : \((.+?)\)\.length = (\d+) :=", txt)})
    lens.update({k: int(v) for k, v in re.findall(r"theorem \w+ : (\w+)\.length = (\d+) :=", txt)})
    ch, unread = G.chunks_of(txt, regs, labs, lens)
    C = [(lo, hi) for lo, hi, _ in ch]
    cok = all(any(a <= lo and hi <= b for a, b in L) or all(hi <= a or b <= lo for a, b in L) for lo, hi in C)
    F.ok &= cok
    F.pred.append((f"chunksOk {lean_pairs(L)} {lean_pairs(C)}", f"{len(C)} s_mem chunks ({unread} not read)", cok))
    if unread:
        F.notes.append(f"{unread} s_mem chunks not read")
    return F, txt


def lean_pairs(xs):
    return "[" + ", ".join(f"({a}, {b})" for a, b in xs) + "]"


def main(wit_dir, out):
    os.makedirs(out, exist_ok=True)
    regen = json.load(open(os.path.join(wit_dir, "regen.json")))
    same = {f["file"] for f in regen["files"] if f["byte_identical"]}
    L, rows = [PRELUDE], []
    nbind = npred = 0
    for fn in sorted(f for f in os.listdir(wit_dir) if re.fullmatch(r"Wit\w*\.lean", f)):
        F, txt = facts(os.path.join(wit_dir, fn))
        ns = f"Fk.{fn[:-5]}"
        bound = fn in same and not has_params(txt)
        L.append(f"\n-- {fn}: {'bound to ' + ns if bound else 'not bound (block has parameters)' if fn in same else 'not bound (not byte-identical)'}")
        if bound:
            for i, v in sorted(F.reg.items()):
                L.append(f"example (z : RegZmms) (f : StatusFlags) : (regsN ({ns}.s0 z f))[{i}]! = {v} := rfl")
            for a, v in sorted(F.word.items()):
                L.append(f"example : wordAt {ns}.block {a - BASE} = {v} := rfl")
            for a, v in sorted(F.byte.items()):
                L.append(f"example : byteAt {ns}.block {a - BASE} = {v} := rfl")
            if F.typedesc is not None:
                L.append(f"example : (({ns}.block.drop {F.typedesc - BASE}).take 56) = @Fk.Data.errorStringPtrType {ns}.host := rfl")
            nbind += len(F.reg) + len(F.word) + len(F.byte) + (F.typedesc is not None)
        for e, why, ok in F.pred:
            L.append(f"example : ({e}) = true := rfl  -- {why}")
            npred += 1
        rows.append({"file": fn, "bound": bound, "python_ok": F.ok, "facts": {"regs": len(F.reg), "words": len(F.word), "bytes": len(F.byte),
                     "typedesc": F.typedesc is not None, "predicates": len(F.pred)}, "notes": F.notes})
    L.append('\n#eval IO.println "GOVAL-CHECK-END"\n')
    open(os.path.join(out, "GoValCheck.lean"), "w").write("\n".join(L))
    # controls: one false predicate of each kind and one false binding
    b = next(r for r in rows if r["bound"] and r["facts"]["words"])
    F, _ = facts(os.path.join(wit_dir, b["file"]))
    a, v = sorted(F.word.items())[0]
    ctl = [PRELUDE,
           "example : (sliceOk 65536 70000 65600 17 16 1) = true := rfl  -- len > cap",
           "example : (objOk 65536 70000 65601 24 8) = true := rfl  -- not aligned",
           "example : (boolOk 2) = true := rfl  -- bool byte 2",
           f"example : wordAt Fk.{b['file'][:-5]}.block {a - BASE} = {v + 1} := rfl  -- wrong word"]
    open(os.path.join(out, "GoValControl.lean"), "w").write("\n".join(ctl) + "\n")
    res = {"schema": "fvphase1c.goval-lean/1", "witnesses": len(rows), "bound": sum(r["bound"] for r in rows),
           "python_violations": [r["file"] for r in rows if not r["python_ok"]], "bindings": nbind, "predicates": npred,
           "notes": {r["file"]: r["notes"] for r in rows if r["notes"]}, "rows": rows}
    json.dump(res, open(os.path.join(out, "goval-facts.json"), "w"), indent=1)
    print(json.dumps({k: v for k, v in res.items() if k != "rows"}, indent=1))
    return 0 if not res["python_violations"] else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1], sys.argv[2]))
