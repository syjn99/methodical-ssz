#!/usr/bin/env python3
"""Write the scratch `main` package that keeps the inventory functions in the ELF.

Usage: keepalive.py <inventory.json> <out main.go>
For every type of set I it takes the method values MarshalSSZTo, SizeSSZ and
UnmarshalSSZ of the pointer type, so the linker keeps the generated bodies.
The binary is never run for a result; main only prints the count.
Python 3 standard library only. Run with python3 -I.
"""
import json
import sys

ALIAS = {
    "github.com/OffchainLabs/prysm/v7/proto/prysm/v1alpha1": "eth",
    "github.com/OffchainLabs/prysm/v7/proto/engine/v1": "enginev1",
}
METHODS = ("MarshalSSZTo", "SizeSSZ", "UnmarshalSSZ")


def main():
    inv = json.load(open(sys.argv[1]))
    used = sorted({t["package"] for t in inv["types"]})
    missing = [p for p in used if p not in ALIAS]
    if missing:
        raise SystemExit(f"no import alias for {missing}")
    lines = ["// Code generated by fv/kraken/gen/keepalive.py. DO NOT EDIT.", "",
             "// Command p1cbin keeps the generated SSZ functions of the phase1c inventory in one ELF.",
             "package main", "", "import (", '\t"fmt"', ""]
    lines += [f'\t{ALIAS[p]} "{p}"' for p in used]
    lines += [")", "", "var keep = []any{"]
    for t in sorted(inv["types"], key=lambda t: (t["package"], t["name"])):
        for m in METHODS:
            lines.append(f"\t(*{ALIAS[t['package']]}.{t['name']}).{m},")
    lines += ["}", "", "func main() {", '\tfmt.Println("p1cbin", len(keep))', "}", ""]
    with open(sys.argv[2], "w") as f:
        f.write("\n".join(lines))
    print(f"{len(inv['types'])} types, {len(inv['types']) * len(METHODS)} method values")


if __name__ == "__main__":
    main()
