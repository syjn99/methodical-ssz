#!/bin/sh
# Write lean/Fk/SHash.lean: the sha256 of every converted .S file that
# Fk/Code.lean includes, as the value of a public definition. Fk.Code imports
# Fk.SHash, so Lake rebuilds Fk.Code (and every proof) when a .S file changes;
# Lake does not track the files `include_x64_rt` reads, and a change in a
# comment alone does not change a module's interface. Run from fv/kraken.
set -eu
{
  echo "module"
  echo "/-! Generated by link/shash.sh: sha256 of link/out/norm/*.S (Lake rebuild trigger). -/"
  echo "@[expose] public def Fk.sHash : List String := ["
  for f in link/out/norm/*.S; do
    echo "  \"$(shasum -a 256 "$f" | cut -d' ' -f1) $(basename "$f")\","
  done
  echo "  \"end\"]"
} > lean/Fk/SHash.lean
